# Sort definitions by dependency; self-recursion stays in one def.
def emit():
    text=''.join(parts)
    for name in ['red', 'left', 'right', 'parent', 'node_key', 'child']:
        text=text.replace('def '+name+'(-K: Data', 'def '+name+'(~K: Data')
        text=re.sub(r'\b'+name+r'\(K,', name+'(~K,', text)
    chunks=re.split(r'(?=^def )',text,flags=re.M)
    header=chunks.pop(0)
    # Type declarations are emitted ahead of definitions.
    for i,c in enumerate(chunks):
        pos=c.find('\ntype ')
        if pos>=0:
            header+=c[pos+1:];chunks[i]=c[:pos]+'\n\n'
    defs={re.match(r'def (\w+)',c).group(1):c for c in chunks}
    out=[header]
    while defs:
        ready=[k for k,v in defs.items() if not (set(re.findall(r'(?<![.\w])(\w+)\(',v.split('\n',1)[1])) & (defs.keys()-{k}))]
        if not ready:raise RuntimeError('cyclic helper dependency: '+str(list(defs)))
        for k in ready:out.append(defs.pop(k))
    (ROOT/'src/containers/balanced_search_tree.bend').write_text(re.sub(r'\b(left|right|parent|red)\(', lambda m:'node_'+m[1]+'(', re.sub(r'\bvalues\b(?!\()', 'payloads', ''.join(out))).rstrip()+'\n')
if __name__=='__main__':emit()
