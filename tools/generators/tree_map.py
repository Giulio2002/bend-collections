def fun(name,params,result,body):
    params=re.sub(r'(?<![+\w])(\w+): (Nat|Bool|K|V|Node<K>|Fix|Search)(?=,|$)', r'+\1: \2', params)
    raw(f'def {name}({P}'+(', '+params if params else '')+f') -> {result}:\n'+body)

# A small source-generation aid for ownership-threaded calls. Each step is
# ([(name,type),...], call). Fresh variable names make every move explicit.
def seq(name,params,result,steps,expr):
    env=dict(params)
    def build(j,known):
        if j==len(steps):return expr
        binds,call=steps[j]
        rest=' '.join(x[1] for x in steps[j+1:])+' '+expr
        newnames={k for k,t in binds}
        captures=[(k,t) for k,t in known.items() if k not in newnames and re.search(r'\b'+re.escape(k)+r'\b',rest)]
        inner=build(j+1,dict(captures+binds))
        n=f'{name}_{j+1}'
        rtype=' & '.join(t for k,t in binds)
        pattern=', '.join('+'+k if t in ['Nat','Bool','Cmp','K','V','Node<K>','Search'] else k for k,t in binds)
        sig=', '.join(('+' if t in ['Nat','Bool','Cmp','K','V','Node<K>','Search'] else '')+k+': '+t for k,t in captures)
        fun(n,(sig+', ' if sig else '')+'pair_result: '+rtype,result,f'  ({pattern}) = pair_result\n  '+inner)
        return f'{n}({A}'+('' if not captures else ', '+', '.join(k for k,t in captures))+', '+call+')'
    body=build(0,env)
    sig=', '.join(('+' if t in ['Nat','Bool','Cmp','K','V','Node<K>','Search'] else '')+k+': '+t for k,t in params)
    fun(name,sig,result,'  '+body)

