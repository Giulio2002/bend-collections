"""Generate the arbitrary-finite-trace proof module for a structure whose state
is Data (no linear arrays). The generated Bend proves, by induction on the
operation list and from the structure's per-operation lemma step_ok, that the
real accumulator runner src.run_acc / src.run refines spec.run and keeps the
invariant. Nothing is assumed: the per-step lemma and the spec are inputs.

Usage:  python3 tools/generators/trace_data.py <config-name>
Regenerates proofs/<id>/trace.bend for the named configuration in CONFIGS.
"""
