#!/usr/bin/env python3
"""Emit the repetitive ChaCha Bend sources (implementation core and proofs).

  python3 tools/generators/chacha_gen.py

Writes, relative to the repository root:
  src/crypto/chacha/core.bend          the unrolled double round, the block
                                       function with a round-count parameter,
                                       the HChaCha20 core, state (de)serialization
  proofs/crypto/chacha/core.bend       the core against spec/crypto/chacha.bend

The hand-written files (src/crypto/chacha/chacha20.bend, the other proofs and
the spec) are not generated.
"""
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SRC = os.path.join(ROOT, 'src/crypto/chacha')
PRF = os.path.join(ROOT, 'proofs/crypto/chacha')

# QUARTERROUND applications of one double round, RFC 8439 section 2.3.
QS = [(0, 4, 8, 12), (1, 5, 9, 13), (2, 6, 10, 14), (3, 7, 11, 15),
      (0, 5, 10, 15), (1, 6, 11, 12), (2, 7, 8, 13), (3, 4, 9, 14)]
CONST = [0x61707865, 0x3320646e, 0x79622d32, 0x6b206574]

ALL = ','.join('a%d' % i for i in range(16))
PALL = ','.join('+a%d' % i for i in range(16))
XS = ','.join('x%d' % i for i in range(16))


def rotl(x, n):
    return 'U32.or(U32.shln(%s,%dn),U32.shrn(%s,%dn))' % (x, n, x, 32 - n)


def quarter_fn(k, q):
    a, b, c, d = q
    fields = ['x%d' % i for i in range(16)]
    pat = ','.join(('+' if i in q else '') + f for i, f in enumerate(fields))
    lines = [
        '+a1 = U32.add(x%d,x%d)' % (a, b),
        '+d1x = U32.xor(x%d,a1)' % d,
        '+d1 = %s' % rotl('d1x', 16),
        '+c1 = U32.add(x%d,d1)' % c,
        '+b1x = U32.xor(x%d,c1)' % b,
        '+b1 = %s' % rotl('b1x', 12),
        '+a2 = U32.add(a1,b1)',
        '+d2x = U32.xor(d1,a2)',
        '+d2 = %s' % rotl('d2x', 8),
        '+c2 = U32.add(c1,d2)',
        '+b2x = U32.xor(b1,c2)',
        '+b2 = %s' % rotl('b2x', 7),
    ]
    out = list(fields)
    out[a], out[b], out[c], out[d] = 'a2', 'b2', 'c2', 'd2'
    body = '\n'.join('      ' + l for l in lines)
    return """# QUARTERROUND(%d, %d, %d, %d).
def qr%d(s: State) -> State:
  match s:
    case S{%s}:
%s
      S{%s}

""" % (a, b, c, d, k, pat, body, ','.join(out))


def double_round():
    cur = ['a%d' % i for i in range(16)]
    lines = []
    for q, (a, b, c, d) in enumerate(QS):
        p = 'q%d' % q
        lines.append('+%sa1 = U32.add(%s,%s)' % (p, cur[a], cur[b]))
        lines.append('+%sd1x = U32.xor(%s,%sa1)' % (p, cur[d], p))
        lines.append('+%sd1 = %s' % (p, rotl(p + 'd1x', 16)))
        lines.append('+%sc1 = U32.add(%s,%sd1)' % (p, cur[c], p))
        lines.append('+%sb1x = U32.xor(%s,%sc1)' % (p, cur[b], p))
        lines.append('+%sb1 = %s' % (p, rotl(p + 'b1x', 12)))
        lines.append('+%sa2 = U32.add(%sa1,%sb1)' % (p, p, p))
        lines.append('+%sd2x = U32.xor(%sd1,%sa2)' % (p, p, p))
        lines.append('+%sd2 = %s' % (p, rotl(p + 'd2x', 8)))
        lines.append('+%sc2 = U32.add(%sc1,%sd2)' % (p, p, p))
        lines.append('+%sb2x = U32.xor(%sb1,%sc2)' % (p, p, p))
        lines.append('+%sb2 = %s' % (p, rotl(p + 'b2x', 7)))
        cur[a], cur[b], cur[c], cur[d] = p + 'a2', p + 'b2', p + 'c2', p + 'd2'
    body = '\n'.join('      ' + l for l in lines)
    return body + '\n      S{%s}' % ','.join(cur)


def octets(w):
    return ['U32.and(%s,255)' % w, 'U32.and(U32.shrn(%s,8n),255)' % w,
            'U32.and(U32.shrn(%s,16n),255)' % w, 'U32.shrn(%s,24n)' % w]


def core():
    out = []
    out.append('''# Generated by tools/generators/chacha_gen.py; do not edit.
# The ChaCha core (RFC 8439 sections 2.1-2.3): the sixteen-word state as a
# record, one double round (four column and four diagonal quarter rounds)
# fully unrolled with constant rotations, and the block function with the
# number of double rounds as a parameter (ChaCha20: 10; ChaCha8: 4;
# ChaCha12: 6). No operation depends on secret data for its control flow or
# memory access: the round count is public and every step is an add, xor or
# constant rotation.
import Base

type State is Data:
  S{%s}

''' % ', '.join('x%d: U32' % i for i in range(16)))
    for k, q in enumerate(QS):
        out.append(quarter_fn(k, q))
    out.append('''# One double round: QUARTERROUND on the columns (0,4,8,12) .. (3,7,11,15),
# then on the diagonals (0,5,10,15) (1,6,11,12) (2,7,8,13) (3,4,9,14).
# (One quarter round per function: the proofs compare one quarter round at a
# time, so that no check has to expand a whole round over symbolic words.)
def double_round(s: State) -> State:
  qr7(qr6(qr5(qr4(qr3(qr2(qr1(qr0(s))))))))

''')
    out.append('''# n double rounds (2n rounds).
def rounds(n: Nat, s: State) -> State:
  match n:
    case 0n: s
    case 1n+p: rounds(p, double_round(s))

# Word-wise sum of two states (the feed-forward).
def add(a: State, b: State) -> State:
  match a b:
    case S{%s} S{%s}:
      S{%s}

# The block function with n double rounds: the rounds, then the input added.
def block(+n: Nat, +s: State) -> State:
  add(s, rounds(n, s))

# The ChaCha20 input state: constants, key, block counter, nonce.
def init(k0: U32, k1: U32, k2: U32, k3: U32, k4: U32, k5: U32, k6: U32, k7: U32, counter: U32, n0: U32, n1: U32, n2: U32) -> State:
  S{%d, %d, %d, %d, k0, k1, k2, k3, k4, k5, k6, k7, counter, n0, n1, n2}

# The HChaCha20 input state: constants, key, the four words of the 16-byte nonce.
def hinit(k0: U32, k1: U32, k2: U32, k3: U32, k4: U32, k5: U32, k6: U32, k7: U32, n0: U32, n1: U32, n2: U32, n3: U32) -> State:
  S{%d, %d, %d, %d, k0, k1, k2, k3, k4, k5, k6, k7, n0, n1, n2, n3}

# The 64 little-endian bytes of a state.
def bytes(s: State) -> List<&2, U32>:
  match s:
    case S{%s}:
      [%s]

# HChaCha20's output: the little-endian bytes of words 0..3 and 12..15.
def hbytes(s: State) -> List<&2, U32>:
  match s:
    case S{%s}:
      [%s]
''' % (XS, ','.join('y%d' % i for i in range(16)), ','.join('U32.add(x%d,y%d)' % (i, i) for i in range(16)),
       CONST[0], CONST[1], CONST[2], CONST[3], CONST[0], CONST[1], CONST[2], CONST[3],
       ','.join('+x%d' % i for i in range(16)), ', '.join(o for i in range(16) for o in octets('x%d' % i)),
       ','.join(('+x%d' % i) if i in (0, 1, 2, 3, 12, 13, 14, 15) else ('x%d' % i) for i in range(16)),
       ', '.join(o for i in (0, 1, 2, 3, 12, 13, 14, 15) for o in octets('x%d' % i))))
    return ''.join(out)


PROOF_HEAD = '''# Generated by tools/generators/chacha_gen.py; do not edit.
# The unrolled ChaCha core refines the list-based RFC 8439 specification.
#
# vec(s) is the RFC state list of a record state, one projection per entry,
# so that the list has its shape even when the state is abstract. One double
# round is compared with inner_block on a destructured state (both sides
# normalize to the same sixteen words); the round count is then an induction,
# so the theorems hold for every number of double rounds (ChaCha20, ChaCha8,
# ChaCha12 alike).
import Base
import ../../../src/crypto/chacha/core.bend as C
import ../../../spec/crypto/chacha.bend as R

'''

PROOF_BODY = '''def vec(+s: C.State) -> List<&2, U32>:
  [@VEC@]

@QRS@
law double_round_correct:
  for +s: C.State
  {vec(C.double_round(s)) == R.inner_block(vec(s)) : List<&2, U32>}

def double_round_correct(s):
@CHAIN@

law rounds_correct:
  for +n: Nat
  for +s: C.State
  {vec(C.rounds(n, s)) == R.inner_blocks(n, vec(s)) : List<&2, U32>}

def rounds_correct(n, s):
  match n:
    case 0n: {==}
    case 1n+p:
      Equal.trans(List<&2, U32>,
        vec(C.rounds(p, C.double_round(s))),
        R.inner_blocks(p, vec(C.double_round(s))),
        R.inner_blocks(p, R.inner_block(vec(s))),
        rounds_correct(p, C.double_round(s)),
        Equal.cong(List<&2, U32>, List<&2, U32>, l => R.inner_blocks(p, l), vec(C.double_round(s)), R.inner_block(vec(s)), double_round_correct(s)))

law add_correct:
  for +a: C.State
  for +b: C.State
  {vec(C.add(a, b)) == R.add_words(vec(a), vec(b)) : List<&2, U32>}

def add_correct(a, b):
  match a b:
    case C.S{@A@} C.S{@B@}: {==}

law bytes_correct:
  for +s: C.State
  {C.bytes(s) == R.serialize(vec(s)) : List<&2, U32>}

def bytes_correct(s):
  match s:
    case C.S{@A@}: {==}

# The block function with n double rounds, serialized, is the RFC's.
law block_correct:
  for +n: Nat
  for +s: C.State
  {C.bytes(C.block(n, s)) == R.serialize(R.add_words(vec(s), R.inner_blocks(n, vec(s)))) : List<&2, U32>}

def block_correct(n, s):
  Equal.trans(List<&2, U32>, C.bytes(C.block(n, s)), R.serialize(vec(C.add(s, C.rounds(n, s)))), R.serialize(R.add_words(vec(s), R.inner_blocks(n, vec(s)))),
    bytes_correct(C.add(s, C.rounds(n, s))),
    Equal.trans(List<&2, U32>, R.serialize(vec(C.add(s, C.rounds(n, s)))), R.serialize(R.add_words(vec(s), vec(C.rounds(n, s)))), R.serialize(R.add_words(vec(s), R.inner_blocks(n, vec(s)))),
      Equal.cong(List<&2, U32>, List<&2, U32>, l => R.serialize(l), vec(C.add(s, C.rounds(n, s))), R.add_words(vec(s), vec(C.rounds(n, s))), add_correct(s, C.rounds(n, s))),
      Equal.cong(List<&2, U32>, List<&2, U32>, l => R.serialize(R.add_words(vec(s), l)), vec(C.rounds(n, s)), R.inner_blocks(n, vec(s)), rounds_correct(n, s))))

law init_correct:
  for +k0: U32
  for +k1: U32
  for +k2: U32
  for +k3: U32
  for +k4: U32
  for +k5: U32
  for +k6: U32
  for +k7: U32
  for +c: U32
  for +n0: U32
  for +n1: U32
  for +n2: U32
  {vec(C.init(k0, k1, k2, k3, k4, k5, k6, k7, c, n0, n1, n2)) == R.state([k0, k1, k2, k3, k4, k5, k6, k7], c, [n0, n1, n2]) : List<&2, U32>}

def init_correct(k0, k1, k2, k3, k4, k5, k6, k7, c, n0, n1, n2):
  {==}

law hinit_correct:
  for +k0: U32
  for +k1: U32
  for +k2: U32
  for +k3: U32
  for +k4: U32
  for +k5: U32
  for +k6: U32
  for +k7: U32
  for +n0: U32
  for +n1: U32
  for +n2: U32
  for +n3: U32
  {vec(C.hinit(k0, k1, k2, k3, k4, k5, k6, k7, n0, n1, n2, n3)) == R.hstate([k0, k1, k2, k3, k4, k5, k6, k7], [n0, n1, n2, n3]) : List<&2, U32>}

def hinit_correct(k0, k1, k2, k3, k4, k5, k6, k7, n0, n1, n2, n3):
  {==}

law hbytes_correct:
  for +s: C.State
  {C.hbytes(s) == R.serialize([R.get(vec(s), 0n), R.get(vec(s), 1n), R.get(vec(s), 2n), R.get(vec(s), 3n), R.get(vec(s), 12n), R.get(vec(s), 13n), R.get(vec(s), 14n), R.get(vec(s), 15n)]) : List<&2, U32>}

def hbytes_correct(s):
  match s:
    case C.S{@A@}: {==}
'''


def proof_core():
    A = ','.join('a%d' % i for i in range(16))
    B = ','.join('b%d' % i for i in range(16))
    out = [PROOF_HEAD]
    for i in range(16):
        out.append('def p%d(s: C.State) -> U32:\n  match s:\n    case C.S{%s}: a%d\n\n' % (i, A, i))
    qrs = []
    for k, (a, b, c, d) in enumerate(QS):
        qrs.append("""law qr%d_correct:
  for +s: C.State
  {vec(C.qr%d(s)) == R.quarter(vec(s), %dn, %dn, %dn, %dn) : List<&2, U32>}

def qr%d_correct(s):
  match s:
    case C.S{%s}: {==}

""" % (k, k, a, b, c, d, k, A))
    def T(k):
        t = 's'
        for j in range(k + 1):
            t = 'C.qr%d(%s)' % (j, t)
        return t
    def Q(k):
        t = 'vec(s)'
        for j in range(k + 1):
            a, b, c, d = QS[j]
            t = 'R.quarter(%s, %dn, %dn, %dn, %dn)' % (t, a, b, c, d)
        return t
    L = 'List<&2, U32>'
    chain = ['  +e0 = qr0_correct(s)']
    for k in range(1, 8):
        a, b, c, d = QS[k]
        chain.append('  +e%d = Equal.trans(%s, vec(%s), R.quarter(vec(%s), %dn, %dn, %dn, %dn), %s, qr%d_correct(%s), Equal.cong(%s, %s, l => R.quarter(l, %dn, %dn, %dn, %dn), vec(%s), %s, e%d))'
                     % (k, L, T(k), T(k - 1), a, b, c, d, Q(k), k, T(k - 1), L, L, a, b, c, d, T(k - 1), Q(k - 1), k - 1))
    chain.append('  e7')
    out.append(PROOF_BODY.replace('@VEC@', ', '.join('p%d(s)' % i for i in range(16)))
               .replace('@A@', A).replace('@B@', B).replace('@QRS@', ''.join(qrs)).replace('@CHAIN@', '\n'.join(chain)))
    return ''.join(out)


def main():
    os.makedirs(SRC, exist_ok=True)
    os.makedirs(PRF, exist_ok=True)
    with open(os.path.join(SRC, 'core.bend'), 'w') as f:
        f.write(core())
    with open(os.path.join(PRF, 'core.bend'), 'w') as f:
        f.write(proof_core())


if __name__ == '__main__':
    main()
