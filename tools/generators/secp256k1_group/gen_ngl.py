# group to itself and commutes with the complete addition, phi(G) is
# [lambda] G, and so phi([k] G) is [lambda] ([k] G) for every k. Every
# clause is for every input; `one` is the number 1 kept symbolic (h1).
# Proved by `bend proofs/crypto/secp256k1/proof_glv.bend`.
#
''' + NOTP,
        phead='''# The GLV endomorphism (laws_glv.bend):
# `bend proofs/crypto/secp256k1/proof_glv.bend`. Each clause is its lemma
# of group/glvp.bend applied to the certificates (group/certpc.bend), to
# G's validity (group/ptv.bend) and to phi(G) equiv [lambda] G
# (group/glvf.bend from the eight chunk facts group/ptg_<i>.bend).
'''),
    'glvsplit': dict(
        lem='glvsplitp', ns='GQ', limp='import ./glvc.bend as GC\nimport ./glvs.bend as GLS\n',
        lhead='''# The GLV decomposition on the multiples of G, as a plain lemma that keeps
# the expensive facts as hypotheses: hp, hc, hg, hn ([n] G is O) and hf
# (phi(G) is [lambda] G). proof_glvsplit.bend applies the certificates.
''',
        head='''# The GLV decomposition of a scalar multiplication on the generator of
# secp256k1: for k == k1 + k2 lambda (mod n), [k] G is [k1] G + [k2] phi(G)
