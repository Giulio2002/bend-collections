NGC = 'PE.ng(one, h1, PC.prime_p(one, h1), PC.cube_spec(one, h1), %s)' % ', '.join('N%d.fact(one, h1)' % i for i in range(1, 9))
HF_T = lambda q, b, l: E(q, 'GV.phi(%s, %s, %s)' % (q, b, G), S(q, l, G))
PHC = ('Lg.subst(Nat, b => %s, X.bvalo(one, GC.betal()), GV.beta(one), GC.beta_is(one, h1), Lg.subst(Nat, l => %s, X.bvalo(one, GC.laml()), GV.lambda(one), GC.lam_is(one, h1), GLF.phi_g(one, h1, PC.prime_p(one, h1), PC.cube_spec(one, h1), %s)))'
       % (HF_T(P, 'b', LA), HF_T(P, 'X.bvalo(one, GC.betal())', 'l'), ', '.join('L%d.fact(one, h1)' % i for i in range(1, 9))))
CLOSE = {'hp': 'PC.prime_p(one, h1)', 'hc': 'PC.cube_spec(one, h1)', 'hq': 'CN.prime_n(one, h1)', 'hg': 'PV.g_valid(one, h1)', 'hn': 'ng(one, h1)', 'hf': 'phig(one, h1)'}
CIMP = {'hp': ['import ./group/certpc.bend as PC'], 'hc': ['import ./group/certpc.bend as PC'], 'hq': ['import ./group/certn.bend as CN'], 'hg': ['import ./group/ptv.bend as PV'],
        'hn': ['import ./group/certpc.bend as PC', 'import ./group/pte.bend as PE'] + ['import ./group/ptn_%d.bend as N%d' % (i, i) for i in range(1, 9)],
        'hf': ['import ./group/certpc.bend as PC', 'import ./group/bnx.bend as X', 'import ./group/glvc.bend as GC', 'import ./group/glvf.bend as GLF', '../../lib/logic.bend as Lg'] + ['import ./group/ptg_%d.bend as L%d' % (i, i) for i in range(1, 9)]}
HELP = {'hn': '# [n] G is O\ndef ng(+one: Nat, +h1: {one == 1n : Nat}) -> %s:\n  %s\n' % (HYP['hn'], NGC),
        'hf': '# phi(G) is [lambda] G\ndef phig(+one: Nat, +h1: {one == 1n : Nat}) -> %s:\n  %s\n' % (HYP['hf'], PHC)}


def main():
    for fam, cfg in FAM.items():
        cl = [c for c in CL if c[0] == fam]
        lem = IMP + cfg['limp'] + '\n' + cfg['lhead']
        laws = LIMP + '\n' + cfg['head']
        used = []
        body = ''
        for _, name, com, hyps, vars_, concl, proof in cl:
            fn = name.lower().replace('.', '_')
            sig = ''.join(', +%s: %s' % (h, HYP[h]) for h in hyps) + ''.join(', +%s: %s' % v for v in vars_)
            lem += '\n# %s\ndef %s(+one: Nat, +h1: {one == 1n : Nat}%s) -> %s:\n  %s\n' % (com, fn, sig, concl, proof)
            laws += '\n# %s\nlaw %s:\n  for +one: Nat\n  for +h1: {one == 1n : Nat}\n%s  %s\n' % (com, name, ''.join('  for +%s: %s\n' % v for v in vars_), concl)
            args = ', '.join(['one', 'h1'] + [v for v, _ in vars_])
            call = ', '.join(['one', 'h1'] + [CLOSE[h] for h in hyps] + [v for v, _ in vars_])
            body += '\ndef Laws.%s(%s):\n  %s.%s(%s)\n' % (name, args, cfg['ns'], fn, call)
            used += [h for h in hyps if h not in used]
        imps = ['import ./laws_%s.bend as Laws' % fam, 'import ./group/%s.bend as %s' % (cfg['lem'], cfg['ns'])]
        need_spec = any(h in used for h in ('hn', 'hf'))
        for h in used:
            for i in CIMP[h]:
                i = i if i.startswith('import ') else 'import ' + i + ''
                if i not in imps:
                    imps.append(i)
        spec = ''
        if need_spec:
            spec = ('import ../../../spec/crypto/secp256k1/field.bend as FS\nimport ../../../spec/crypto/secp256k1/curve.bend as CS\n'
                    'import ../../../spec/crypto/secp256k1/group.bend as GS\nimport ../../../spec/crypto/secp256k1/glv.bend as GV\n')
        imps = [i.replace('import ../../lib/logic.bend as Lg', 'import ../../lib/logic.bend as Lg') for i in imps]
        proof = HEAD + 'import Base\n' + spec + '\n'.join(imps) + '\n\n' + cfg['phead'] + ''.join('\n' + HELP[h] for h in used if h in HELP) + body
        open(os.path.join(D, 'group', cfg['lem'] + '.bend'), 'w').write(HEAD + lem)
        open(os.path.join(D, 'laws_%s.bend' % fam), 'w').write(HEAD + laws)
        open(os.path.join(D, 'proof_%s.bend' % fam), 'w').write(proof)


if __name__ == '__main__':
    main()
