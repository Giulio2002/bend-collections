'''),
    'glv': dict(
        lem='glvp', ns='GP', limp='import ./glv.bend as GLV\nimport ./glvc.bend as GC\n',
        lhead='''# The GLV endomorphism of secp256k1 on the specification's constants
# (spec/crypto/secp256k1/glv.bend), as plain lemmas that keep the expensive
# facts as hypotheses: hp, hc as in group/glawp.bend, hg (G is a point of
# the group) and hf (phi(G) is [lambda] G). proof_glv.bend applies the
