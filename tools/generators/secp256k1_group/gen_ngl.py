''',
        head='''# The generator G of secp256k1 (spec/crypto/secp256k1/curve.bend, g) has
# order exactly n = FS.order(one), in the group of
# spec/crypto/secp256k1/group.bend (valid, equiv, smul): G is a point of
# the group, [n] G is O, [k] G depends only on k modulo n, and [k] G is not
# O for 0 < k < n. Every clause is for every input; `one` is the number 1
# kept symbolic (h1). Proved by `bend proofs/crypto/secp256k1/proof_order.bend`
# from the certificates that p and n are prime and that -7 is not a cube
