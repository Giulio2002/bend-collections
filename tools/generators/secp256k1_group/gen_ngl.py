# That needs every point of the curve to be a multiple of G, i.e.
# #E(F_p) = n (point counting), which is not proved here.
'''
FAM = {
    'order': dict(
        lem='orderp', ns='OP', limp='import ./ptv.bend as PV\nimport ./pto.bend as PO\nimport ./ptw.bend as PW\n',
        lhead='''# The order of the generator G of secp256k1, as plain lemmas that keep the
# expensive facts as hypotheses: hp (p is prime) and hc ((-7)^((p-1)/3) != 1)
