def spec_chain(v, quads, xs):
    e = v
    for k, (a, b, c, d) in enumerate(quads):
        e = 'S.G(%s,%dn,%dn,%dn,%dn,%s,%s)' % (e, a, b, c, d, xs[2 * k], xs[2 * k + 1])
    return e


def compress_proof():
    xs = ws(8, 'x')
    ms = ws(16, 'm')
    pat = 'T.V{%s}' % csv('T.W{l%d,u%d}' % (i, i) for i in range(16))
    s = HEADER + ('import Base\nimport ../../../../src/crypto/blake/blake2b/types.bend as T\n'
                  'import ../../../../src/crypto/blake/blake2b/compress.bend as I\nimport ../../../../spec/crypto/blake/blake2b.bend as S\n\n')
    mlist = '[%s]' % csv(ms)
    for r in range(ROUNDS):
        for nm, quads in (('column%d' % r, COLS), ('diagonal%d' % r, DIAGS)):
            s += 'law %s_correct:\n  for +v: T.State\n' % nm
            s += ''.join('  for +%s: T.Lane\n' % x for x in xs)
            s += '  {I.%s(v,%s) == %s : T.State}\n\n' % (nm, csv(xs), spec_chain('v', quads, xs))
            s += 'def %s_correct(v,%s):\n  match v %s:\n    case %s %s: {==}\n\n' % (
                nm, csv(xs), ' '.join(xs), pat, ' '.join('T.W{p%d,q%d}' % (i, i) for i in range(8)))
        sg = SIGMA[r % 10]
        cx = ['m%d' % sg[j] for j in range(8)]
        dx = ['m%d' % sg[j] for j in range(8, 16)]
        colS = spec_chain('v', COLS, cx)
        s += 'law round%d_correct:\n  for +v: T.State\n' % r
        s += ''.join('  for +%s: T.Lane\n' % m for m in ms)
        s += '  {I.round%d(v,%s) == S.round(v,%s,S.sigma(%dn)) : T.State}\n\n' % (r, csv(ms), mlist, r % 10)
        s += 'def round%d_correct(v,%s):\n' % (r, csv(ms))
        s += '  Equal.trans(T.State,\n'
        s += '    I.diagonal%d(I.column%d(v,%s),%s),\n' % (r, r, csv(cx), csv(dx))
        s += '    I.diagonal%d(%s,%s),\n' % (r, colS, csv(dx))
        s += '    %s,\n' % spec_chain(colS, DIAGS, dx)
        s += '    Equal.cong(T.State,T.State,t => I.diagonal%d(t,%s),I.column%d(v,%s),%s,column%d_correct(v,%s)),\n' % (
            r, csv(dx), r, csv(cx), colS, r, csv(cx))
        s += '    diagonal%d_correct(%s,%s))\n\n' % (r, colS, csv(dx))
    # twelve rounds, innermost first
    s += 'law rounds_correct:\n  for +v: T.State\n' + ''.join('  for +%s: T.Lane\n' % m for m in ms)
    s += '  {I.rounds(v,%s) == S.rounds(12n,0n,v,%s) : T.State}\n\n' % (csv(ms), mlist)
    # left side after k rounds (impl) and right side after k rounds (spec)
    def imp(k):
        e = 'v'
        for r in range(k):
            e = 'I.round%d(%s,%s)' % (r, e, csv(ms))
        return e

    def spc(k):
        e = 'v'
        for r in range(k):
            e = 'S.round(%s,%s,S.sigma(%dn))' % (e, mlist, r % 10)
        return e

    def mixed(k, n):
        # impl rounds k..n-1 applied to the spec result of the first k rounds
        e = spc(k)
        for r in range(k, n):
            e = 'I.round%d(%s,%s)' % (r, e, csv(ms))
        return e
    s += 'def rounds_correct(v,%s):\n' % csv(ms)
    # chain: mixed(0,12) -> mixed(1,12) -> ... -> mixed(12,12)=spc(12)
    s += '  %s\n\n' % chain_rounds(mixed, spc, ms, mlist, 12)
