def chain_rounds(mixed, spc, ms, mlist, n):
    # Proves mixed(0,n) == spc(n) by n steps; step k turns round k of the impl into the spec round.
    def step(k):
        # {mixed(k,n) == mixed(k+1,n)}: replace I.round_k(spc(k)) by S.round(spc(k),..)
        inner_i = 'I.round%d(%s,%s)' % (k, spc(k), csv(ms))
        inner_s = 'S.round(%s,%s,S.sigma(%dn))' % (spc(k), mlist, k % 10)
        ctx = 'x'
        for r in range(k + 1, n):
            ctx = 'I.round%d(%s,%s)' % (r, ctx, csv(ms))
        pf = 'round%d_correct(%s,%s)' % (k, spc(k), csv(ms))
        if k + 1 == n:
            return pf
        return 'Equal.cong(T.State,T.State,x => %s,%s,%s,%s)' % (ctx, inner_i, inner_s, pf)
    e = step(n - 1)
    for k in range(n - 2, -1, -1):
        e = 'Equal.trans(T.State,%s,%s,%s,\n    %s,\n    %s)' % (mixed(k, n), mixed(k + 1, n), spc(n), step(k), e)
    return e


