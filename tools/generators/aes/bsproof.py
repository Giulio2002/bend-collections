def circuit_fn(name, out, ret='Bool'):
    """the S-box circuit on the bits b0..b7 of a byte (x0 = b7)"""
    L = ['def %s(%s) -> %s:' % (name, ', '.join('+b%d: Bool' % i for i in range(8)), ret)]
    for i in range(8):
        L.append('  +x%d = b%d' % (i, 7 - i))
    for line in CIRC:
        lhs, rhs = [s.strip() for s in line.split('=')]
        a, op, b = rhs.split()
        f = 'Bool.xor' if op == '^' else 'Bool.and'
        if b.startswith('~'):
            b = 'Bool.xor(True{}, %s)' % b[1:]
        L.append('  +%s = %s(%s, %s)' % (lhs, f, a, b))
    L.append('  %s' % out)
    return L


def enum_cases(vs, body='{==}', indent='  '):
    L = [indent + 'match %s:' % ' '.join(vs)]
    for combo in itertools.product(['True{}', 'False{}'], repeat=len(vs)):
        L.append(indent + '  case %s:' % ' '.join(combo))
        L.append(indent + '    ' + body)
    return L


