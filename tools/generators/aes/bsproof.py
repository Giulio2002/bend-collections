def xt_bit(b, k):
    """bit k of xtime of a byte with bits b(0..7) (Bool expression text)"""
    if k == 0:
        return b(7)
    if k in (1, 3, 4):
        return 'Bool.xor(%s, %s)' % (b(k - 1), b(7))
    return b(k - 1)


def m3_bit(b, k):
    return 'Bool.xor(%s, %s)' % (xt_bit(b, k), b(k))


def op_bit(op, b, k):
    return {'x': xt_bit, 'm': m3_bit, 'p': lambda b, k: b(k)}[op](b, k)


def canon_rename(exprs):
    """rename the variables of some Bool expressions to v0, v1, ... in order of
    first appearance; returns (renamed expressions, the original names)"""
    order = []
    for e in exprs:
        for v in leaves(e):
            if v not in order:
                order.append(v)
    m = {v: ('v', 'v%d' % k) for k, v in enumerate(order)}

    def rn(e):
        if e[0] == 'v':
            return m[e[1]]
        if e[0] == 'c':
            return e
        return (e[0],) + tuple(rn(x) for x in e[1:])
    return [rn(e) for e in exprs], order


def parse_bool(t):
    """parse a Bool expression printed by show / op_bit (Bool.xor(a, b), names)"""
    t = t.strip()
    for op in ('xor', 'and', 'or'):
        pre = 'Bool.%s(' % op
        if t.startswith(pre):
            body = t[len(pre):-1]
            depth = 0
            for k, ch in enumerate(body):
                if ch == '(':
                    depth += 1
                elif ch == ')':
                    depth -= 1
                elif ch == ',' and depth == 0:
                    return (op, parse_bool(body[:k]), parse_bool(body[k + 1:]))
    if t.startswith('Bool.not('):
        return ('not', parse_bool(t[9:-1]))
    if t == 'True{}':
        return T
    if t == 'False{}':
        return F
    return ('v', t)


def mix_lemmas():
    planes = [[var('D.bit(%s, %dn)' % (byte_name(*pos_byte(p)), i)) for p in N32] for i in range(8)]
