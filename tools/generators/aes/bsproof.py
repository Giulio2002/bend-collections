def mix_sym(q):
    def rot8(x):
        return wor(shr(x, 8), shl(x, 24))

    def rot16(x):
        return wor(shl(x, 16), shr(x, 16))
    r = [rot8(x) for x in q]
    a = q
    t7 = wxor(a[7], r[7])
    X = wxor
    return [X(X(t7, r[0]), rot16(X(a[0], r[0]))),
            X(X(X(X(a[0], r[0]), t7), r[1]), rot16(X(a[1], r[1]))),
            X(X(X(a[1], r[1]), r[2]), rot16(X(a[2], r[2]))),
            X(X(X(X(a[2], r[2]), t7), r[3]), rot16(X(a[3], r[3]))),
            X(X(X(X(a[3], r[3]), t7), r[4]), rot16(X(a[4], r[4]))),
            X(X(X(a[4], r[4]), r[5]), rot16(X(a[5], r[5]))),
            X(X(X(a[5], r[5]), r[6]), rot16(X(a[6], r[6]))),
            X(X(X(a[6], r[6]), r[7]), rot16(X(a[7], r[7])))]


