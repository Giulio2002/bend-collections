def ws(p, n, plus=''):
    return ','.join('%s%s%d' % (plus, p, i) for i in range(n))


def params(p, n, ty='U32', plus=''):
    return ','.join('%s%s%d: %s' % (plus, p, i, ty) for i in range(n))


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        f.write(text)
    print('wrote', os.path.relpath(path, ROOT))


