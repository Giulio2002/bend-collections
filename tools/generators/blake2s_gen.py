def mlist():
    return '[%s]' % ','.join('m%d' % i for i in range(16))


def perm(r):
    return ','.join('m%d' % j for j in SIGMA[r])


def tail_expr(k, v):
    e = v
    for r in range(k, ROUNDS):
        e = 'C.round(%s,%s)' % (e, perm(r))
    return e


def gen_compress_proof():
    M = mlist()
    ms = ws('m', 16)
    mfor = ['  for +m%d: U32' % i for i in range(16)]
    L = ['# Generated by tools/generators/blake2s_gen.py; do not edit.',
         '# The unrolled compression function refines the list-based RFC 7693 F.',
         '#',
         '# The implementation runs ten explicit rounds. A proof-side model runs the',
         '# same round function r times, selecting the permuted words by round index;',
         '# for an abstract r both the model and the specification stay symbolic, so',
         '# every comparison below is between one round at most. The theorem is then',
         '# instantiated at r = 10, where the model coincides with the implementation.',
         'import Base',
         'import ../../../../src/crypto/blake/blake2s/types.bend as T',
         'import ../../../../src/crypto/blake/blake2s/compress.bend as C',
         'import ../../../../spec/crypto/blake/blake2s.bend as R',
         '',
         '# The work vector as the RFC list v[0..15], one projection per entry, so',
         '# that the list has its shape even when the vector is abstract.']
    for i in range(16):
        L += ['def p%d(v: T.Vector) -> U32:' % i, '  match v:',
              '    case T.V{%s}: a%d' % (ws('a', 16), i), '']
    L += ['def vec(+v: T.Vector) -> List<&2,U32>:',
          '  [%s]' % ','.join('p%d(v)' % i for i in range(16)), '']
    # model
    L.append('# Model: round i of the implementation reads the words in SIGMA[i mod 10] order.')
    L.append('def round_at(i: Nat, v: T.Vector,%s) -> T.Vector:' % params('m', 16, plus='+'))
    L.append('  match i:')
    for r in range(ROUNDS):
        L.append('    case %dn: C.round(v,%s)' % (r, perm(r)))
    L.append('    case 10n+p: round_at(p,v,%s)' % ms)
    L.append('')
    L.append('def rounds(n: Nat, +i: Nat, v: T.Vector,%s) -> T.Vector:' % params('m', 16, plus='+'))
    L.append('  match n:')
    L.append('    case 0n: v')
    L.append('    case 1n+p: rounds(p,1n+i,round_at(i,v,%s),%s)' % (ms, ms))
    L.append('')
    L.append('def model(+r: Nat, +h: T.State,%s,t0: U32,t1: U32,last: Bool) -> T.State:' % params('m', 16, plus='+'))
    L.append('  C.finish(h,rounds(r,0n,C.init(h,t0,t1,last),%s))' % ms)
    L.append('')
    # per-round lemmas
    for r in range(ROUNDS):
        L += ['law round%d_correct:' % r, '  for +v: T.Vector'] + mfor
        L += ['  {vec(round_at(%dn,v,%s)) == R.round(vec(v),R.sigma(%dn),%s) : List<&2,U32>}' % (r, ms, r, M), '',
              'def round%d_correct(v,%s):' % (r, ms),
              '  match v:',
              '    case T.V{%s}: {==}' % ws('a', 16), '']
    L += ['law round_correct:', '  for +i: Nat', '  for +v: T.Vector'] + mfor
    L += ['  {vec(round_at(i,v,%s)) == R.round(vec(v),R.sigma(i),%s) : List<&2,U32>}' % (ms, M), '',
          'def round_correct(i,v,%s):' % ms, '  match i:']
    for r in range(ROUNDS):
        L.append('    case %dn: round%d_correct(v,%s)' % (r, r, ms))
    L += ['    case 10n+p: round_correct(p,v,%s)' % ms, '']
    # rounds, by induction on an abstract count
    L += ['law rounds_correct:', '  for +n: Nat', '  for +i: Nat', '  for +v: T.Vector'] + mfor
    L += ['  {vec(rounds(n,i,v,%s)) == R.rounds(n,i,vec(v),%s) : List<&2,U32>}' % (ms, M), '',
          'def rounds_correct(n,i,v,%s):' % ms,
          '  match n:',
          '    case 0n: {==}',
          '    case 1n+p:',
          '      Equal.trans(List<&2,U32>,',
          '        vec(rounds(p,1n+i,round_at(i,v,%s),%s)),' % (ms, ms),
          '        R.rounds(p,1n+i,vec(round_at(i,v,%s)),%s),' % (ms, M),
          '        R.rounds(p,1n+i,R.round(vec(v),R.sigma(i),%s),%s),' % (M, M),
          '        rounds_correct(p,1n+i,round_at(i,v,%s),%s),' % (ms, ms),
          '        Equal.cong(List<&2,U32>,List<&2,U32>,x => R.rounds(p,1n+i,x,%s),vec(round_at(i,v,%s)),R.round(vec(v),R.sigma(i),%s),round_correct(i,v,%s)))' % (M, ms, M, ms),
          '']
    # finish / init
    hs = ws('h', 8)
    H = 'T.H{%s}' % hs
    L += ['def fin(%s,+l: List<&2,U32>) -> T.State:' % params('h', 8),
          '  T.H{%s}' % ','.join('U32.xor(U32.xor(h%d,R.get(l,%dn)),R.get(l,%dn))' % (i, i, i + 8) for i in range(8)),
          '',
          'law finish_correct:'] + ['  for +h%d: U32' % i for i in range(8)] + [
          '  for +v: T.Vector',
          '  {C.finish(%s,v) == fin(%s,vec(v)) : T.State}' % (H, hs), '',
          'def finish_correct(%s,v):' % hs,
          '  match v:',
          '    case T.V{%s}: {==}' % ws('a', 16), '']
    V2 = '[%s,%d,%d,%d,%d,U32.xor(%d,t0),U32.xor(%d,t1),%d,%d]' % (hs, IV[0], IV[1], IV[2], IV[3], IV[4], IV[5], IV[6], IV[7])
    L += ['law init_correct:'] + ['  for +h%d: U32' % i for i in range(8)] + [
          '  for +t0: U32', '  for +t1: U32', '  for +last: Bool',
          '  {vec(C.init(%s,t0,t1,last)) == R.invert(last,%s) : List<&2,U32>}' % (H, V2), '',
          'def init_correct(%s,t0,t1,last):' % hs,
          '  match last:',
          '    case True{}: {==}',
          '    case False{}: {==}', '']
    X = 'rounds(r,0n,C.init(%s,t0,t1,last),%s)' % (H, ms)
    I = 'C.init(%s,t0,t1,last)' % H
    L += ['law model_correct:', '  for +r: Nat', '  for +h: T.State'] + mfor + [
          '  for +t0: U32', '  for +t1: U32', '  for +last: Bool',
          '  {model(r,h,%s,t0,t1,last) == R.compress(r,h,%s,t0,t1,last) : T.State}' % (ms, M), '',
          'def model_correct(r,h,%s,t0,t1,last):' % ms,
          '  match h:',
          '    case T.H{%s}:' % hs,
          '      Equal.trans(T.State,',
          '        C.finish(%s,%s),' % (H, X),
          '        fin(%s,vec(%s)),' % (hs, X),
          '        R.compress(r,%s,%s,t0,t1,last),' % (H, M),
          '        finish_correct(%s,%s),' % (hs, X),
          '        Equal.trans(T.State,',
          '          fin(%s,vec(%s)),' % (hs, X),
          '          fin(%s,R.rounds(r,0n,vec(%s),%s)),' % (hs, I, M),
          '          R.compress(r,%s,%s,t0,t1,last),' % (H, M),
          '          Equal.cong(List<&2,U32>,T.State,l => fin(%s,l),vec(%s),R.rounds(r,0n,vec(%s),%s),rounds_correct(r,0n,%s,%s)),' % (hs, X, I, M, I, ms),
          '          Equal.cong(List<&2,U32>,T.State,l => fin(%s,R.rounds(r,0n,l,%s)),vec(%s),R.invert(last,%s),init_correct(%s,t0,t1,last))))' % (hs, M, I, V2, hs),
          '']
    L += ['# F as implemented (ten unrolled rounds) is F of the specification with r = 10.',
          'law compress_correct:', '  for +h: T.State'] + mfor + [
          '  for +t0: U32', '  for +t1: U32', '  for +last: Bool',
          '  {C.compress(h,%s,t0,t1,last) == R.compress(10n,h,%s,t0,t1,last) : T.State}' % (ms, M), '',
          'def compress_correct(h,%s,t0,t1,last):' % ms,
          '  Equal.trans(T.State,C.compress(h,%s,t0,t1,last),model(10n,h,%s,t0,t1,last),R.compress(10n,h,%s,t0,t1,last),' % (ms, ms, M),
          '    {==},model_correct(10n,h,%s,t0,t1,last))' % ms, '']
    write(os.path.join(PRF, 'compress.bend'), '\n'.join(L))


