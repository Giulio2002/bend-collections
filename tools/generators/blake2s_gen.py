def u32word(xs):
    s = 'WNil{}'
    for x in reversed(xs):
        s = 'WCon{%s, %s}' % (x, s)
    return 'U32{%s}' % s


def gen_bytes_proof():
    N = 32
    ys = ['y%d' % i for i in range(N)]
    zs = ['z%d' % i for i in range(N)]
    xs = ['x%d' % i for i in range(N)]
    L = ['# Generated by tools/generators/blake2s_gen.py; do not edit.',
         '# Bytes and words: the specification reassembles block words from',
         '# little-endian bytes and zero-pads the last block byte by byte; the',
         '# implementation reads whole words and masks the last partial word.',
         '# The bit-level facts are proven on the 32 Bool digits of a U32.',
         'import Base',
         'import ../../../../src/crypto/blake/blake2s/blake2s.bend as K',
         'import ../../../../spec/crypto/blake/blake2s.bend as R',
         '',
         '# Two words are equal when their digits are.',
         'law bits32:']
