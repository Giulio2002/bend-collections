def gen_api():
    L = ['# Generated by tools/generators/blake2s_gen.py; do not edit.',
         'import Base', 'import ./types.bend as T', 'import ./compress.bend as C', '']
    # counter
    L += ['# The 64-bit byte counter t is kept as two U32 halves (t0 low, t1 high).',
          'def carry(c: Bool, hi: U32) -> U32:',
          '  match c:',
          '    case True{}: U32.add(hi,1)',
          '    case False{}: hi',
          '',
          'def count_hi(+lo: U32, hi: U32, +n: U32) -> U32:',
          '  carry(U32.is_lt(U32.add(lo,n),n),hi)',
          '']
    # full block reads
    L.append('def read15(+index: U32, h: T.State, t0: U32, t1: U32, %s, pair: Array<U32> & U32) -> Array<U32> & T.State:' % params('w', 15))
    L.append('  (a,w15) = pair')
    L.append('  (a,C.compress(h,%s,t0,t1,False{}))' % ws('w', 16))
    L.append('')
    for k in range(14, -1, -1):
        pw = (', ' + params('w', k)) if k else ''
        L.append('def read%d(+index: U32, h: T.State, t0: U32, t1: U32%s, pair: Array<U32> & U32) -> Array<U32> & T.State:' % (k, pw))
        L.append('  (a,w%d) = pair' % k)
        L.append('  read%d(index,h,t0,t1,%s,Array.get(U32,a,U32.add(index,%d)))' % (k + 1, ws('w', k + 1), k + 1))
        L.append('')
    L += ['def absorb(a: Array<U32>, +index: U32, h: T.State, t0: U32, t1: U32) -> Array<U32> & T.State:',
          '  read0(index,h,t0,t1,Array.get(U32,a,index))', '']
    # final block
    L += ['# The final block keeps the bytes before the logical length and zeroes the rest.',
          '# keep(n, w) keeps the low n bytes of w.',
          'def keep(n: Nat, +w: U32) -> U32:',
          '  match n:',
          '    case 0n: 0',
          '    case 1n: U32.and(255,w)',
          '    case 2n: U32.and(65535,w)',
          '    case 3n: U32.and(16777215,w)',
          '    case 4n+p: w',
          '',
          'def pad_word(w: U32, +pos: Nat, +remain: Nat) -> U32:',
          '  keep(Nat.sub(remain,pos),w)',
          '']
    L.append('def pad15(+remain: Nat, +index: U32, h: T.State, t0: U32, t1: U32, %s, pair: Array<U32> & U32) -> T.State:' % params('w', 15))
    L.append('  (a,w15) = pair')
    L.append('  C.compress(h,%s,t0,t1,True{})' % ','.join('pad_word(w%d,%dn,remain)' % (i, 4 * i) for i in range(16)))
    L.append('')
    for k in range(14, -1, -1):
        pw = (', ' + params('w', k)) if k else ''
        L.append('def pad%d(+remain: Nat, +index: U32, h: T.State, t0: U32, t1: U32%s, pair: Array<U32> & U32) -> T.State:' % (k, pw))
        L.append('  (a,w%d) = pair' % k)
        L.append('  pad%d(remain,index,h,t0,t1,%s,Array.get(U32,a,U32.add(index,%d)))' % (k + 1, ws('w', k + 1), k + 1))
        L.append('')
    L += ['def finish(a: Array<U32>, +index: U32, +t0: U32, t1: U32, +remain: Nat, h: T.State) -> T.State:',
          '  +n = U32.from_nat(remain)',
          '  pad0(remain,index,h,U32.add(t0,n),count_hi(t0,t1,n),Array.get(U32,a,index))',
          '',
          'def blocks(n: Nat, +index: U32, +t0: U32, t1: U32, +remain: Nat, pair: Array<U32> & T.State) -> T.State:',
          '  match n pair:',
          '    case 0n Tuple{a,h}: finish(a,index,t0,t1,remain,h)',
          '    case 1n+p Tuple{a,h}:',
          '      +c0 = U32.add(t0,64)',
          '      +c1 = count_hi(t0,t1,64)',
          '      blocks(p,U32.add(index,16),c0,c1,remain,absorb(a,index,h,c0,c1))',
          '',
          '# Parameter block for an unkeyed 32-byte digest: h0 = IV0 ^ 0x01010020.',
          'def initial() -> T.State:',
          '  T.H{%s}' % ','.join(str(x) for x in [IV[0] ^ 0x01010020] + IV[1:]),
          '',
          '# Blocks before the last one: max(1, ceil(length/64)) - 1.',
          'def leading(length: Nat) -> Nat:',
          '  Nat.sub(Nat.div(Nat.add(length,63n),64n),1n)',
          '',
          'def unchecked(a: Array<U32>, +length: Nat) -> T.State:',
          '  +n = leading(length)',
          '  blocks(n,0,0,0,Nat.sub(length,Nat.mul(64n,n)),(a,initial()))',
          '',
          'def digest(h: T.State) -> Array<U32>:',
          '  match h:',
          '    case T.H{%s}:' % ws('h', 8),
          '      a = Array.new(U32,3n,0)']
    for i in range(8):
        L.append('      a = Array.set(U32,a,%d,h%d)' % (i, i))
    L += ['      a', '',
          'def checked(valid: Bool, a: Array<U32>, length: Nat) -> Maybe<&1,Array<U32>>:',
          '  match valid:',
          '    case False{}: None{}',
          '    case True{}: Some{digest(unchecked(a,length))}',
          '',
          'def sized(+length: Nat, pair: Array<U32> & U32) -> Maybe<&1,Array<U32>>:',
          '  (a,capacity) = pair',
          '  checked(Nat.is_le(length,Nat.mul(4n,U32.to_nat(capacity))),a,length)',
          '',
          '# BLAKE2s-256 of the first `length` bytes of `a` (four little-endian bytes per',
          '# word): the eight little-endian digest words, or None when length exceeds',
          '# 4 * the array capacity.',
          'def blake2s(a: Array<U32>, length: Nat) -> Maybe<&1,Array<U32>>:',
          '  sized(length,Array.size(U32,a))',
          '']
    write(os.path.join(SRC, 'blake2s.bend'), '\n'.join(L))




