def rotr(x, n):
    return 'U32.or(U32.shrn(%s,%dn),U32.shln(%s,%dn))' % (x, n, x, 32 - n)


def gen_compress():
    L = ['# Generated by tools/generators/blake2s_gen.py; do not edit.',
         '# BLAKE2s compression function F (RFC 7693 section 3.2). One round is fully',
         '# unrolled (eight G steps, constant rotations); each round index selects the',
         '# SIGMA-permuted message words by a branch, never by a run-time table.',
         'import Base', 'import ./types.bend as T', '']
    # round: v record in, x0..x15 = message words in schedule order
    L.append('def round(v: T.Vector,%s) -> T.Vector:' % params('x', 16))
    L.append('  match v:')
    L.append('    case T.V{%s}:' % ws('a', 16, '+'))
    cur = ['a%d' % i for i in range(16)]
    k = 0
    for gi, (a, b, c, d) in enumerate(GS):
        x, y = 'x%d' % (2 * gi), 'x%d' % (2 * gi + 1)
        va, vb, vc, vd = cur[a], cur[b], cur[c], cur[d]
        n = lambda: 't%d' % (len(L))
        a1 = 'g%da1' % gi; d1 = 'g%dd1' % gi; c1 = 'g%dc1' % gi; b1 = 'g%db1' % gi
        a2 = 'g%da2' % gi; d2 = 'g%dd2' % gi; c2 = 'g%dc2' % gi; b2 = 'g%db2' % gi
        def rot(dst, p, q, n):
            L.append('      +%sx = U32.xor(%s,%s)' % (dst, p, q))
            L.append('      +%s = %s' % (dst, rotr(dst + 'x', n)))
        L.append('      +%s = U32.add(U32.add(%s,%s),%s)' % (a1, va, vb, x))
        rot(d1, vd, a1, 16)
        L.append('      +%s = U32.add(%s,%s)' % (c1, vc, d1))
        rot(b1, vb, c1, 12)
        L.append('      +%s = U32.add(U32.add(%s,%s),%s)' % (a2, a1, b1, y))
        rot(d2, d1, a2, 8)
        L.append('      +%s = U32.add(%s,%s)' % (c2, c1, d2))
        rot(b2, b1, c2, 7)
        cur[a], cur[b], cur[c], cur[d] = a2, b2, c2, d2
    L.append('      T.V{%s}' % ','.join(cur))
    L.append('')
    # init
    L.append('def flag(last: Bool) -> U32:')
    L.append('  match last:')
    L.append('    case True{}: %d' % (IV[6] ^ 0xFFFFFFFF))
    L.append('    case False{}: %d' % IV[6])
    L.append('')
    L.append('def init(h: T.State,t0: U32,t1: U32,last: Bool) -> T.Vector:')
    L.append('  match h:')
    L.append('    case T.H{%s}:' % ws('h', 8))
    L.append('      T.V{%s,%d,%d,%d,%d,U32.xor(%d,t0),U32.xor(%d,t1),flag(last),%d}' % (
        ws('h', 8), IV[0], IV[1], IV[2], IV[3], IV[4], IV[5], IV[7]))
    L.append('')
    L.append('def finish(h: T.State,v: T.Vector) -> T.State:')
    L.append('  match h v:')
    L.append('    case T.H{%s} T.V{%s}:' % (ws('h', 8), ws('v', 16)))
    L.append('      T.H{%s}' % ','.join('U32.xor(U32.xor(h%d,v%d),v%d)' % (i, i, i + 8) for i in range(8)))
    L.append('')
    L.append('# F(h, m, t, f): ten rounds, round r reading the words in SIGMA[r] order.')
    L.append('def compress(+h: T.State,%s,t0: U32,t1: U32,last: Bool) -> T.State:' % params('m', 16, plus='+'))
    e = 'init(h,t0,t1,last)'
    for r in range(ROUNDS):
        e = 'round(%s,%s)' % (e, perm(r))
    L.append('  finish(h,%s)' % e)
    L.append('')
    write(os.path.join(SRC, 'compress.bend'), '\n'.join(L))


