# SHA-512 (FIPS 180-4) on byte lists. A 64-bit word is two native U32 halves
# (T.W{hi, lo}); every rotation is fused into its two half-word expressions,
# the message schedule lives in a rolling window of the last sixteen words
# (no 80-word list is built), and the round constants are one list walked
# once per block. Proved equal to spec/crypto/sha512.bend for every input in
