"""Generate src/crypto/sha512/core.bend and proofs/crypto/sha512/conformance.bend.

  python3 tools/generators/sha512_gen.py

The implementation's fused rotations, the FIPS 180-4 constants (computed here
from the cube and square roots of the first primes, exactly, with integer
roots) and the proof's case enumerations are mechanical, so they are written
by this script. The specification spec/crypto/sha512.bend is written by hand
and is not generated.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def iroot(n, k):
    lo, hi = 0, 1 << ((n.bit_length() // k) + 2)
    while lo < hi:
        m = (lo + hi + 1) // 2
        if m ** k <= n:
            lo = m
        else:
            hi = m - 1
    return lo


def primes(n):
    ps, x = [], 2
    while len(ps) < n:
        if all(x % p for p in ps):
            ps.append(x)
        x += 1
    return ps


PS = primes(80)
K = [iroot(p << 192, 3) % (1 << 64) for p in PS]          # FIPS 180-4 4.2.3
H0 = [iroot(p << 128, 2) % (1 << 64) for p in PS[:8]]     # FIPS 180-4 5.3.5
assert K[0] == 0x428a2f98d728ae22 and K[79] == 0x6c44198c4a475817
assert H0[0] == 0x6a09e667f3bcc908 and H0[7] == 0x5be0cd19137e2179


def lane(v):
    return 'T.W{%d, %d}' % (v >> 32, v & 0xffffffff)


def rot(n):
    """(hi, lo) expressions of ROTR^n(W{hi, lo}), exactly as the spec's rotr unfolds."""
    if n < 32:
        return ('U32.or(U32.shrn(hi, %dn), U32.shln(lo, %dn))' % (n, 32 - n),
                'U32.or(U32.shrn(lo, %dn), U32.shln(hi, %dn))' % (n, 32 - n))
    m = n - 32
    return ('U32.or(U32.shrn(lo, %dn), U32.shln(hi, %dn))' % (m, 32 - m),
            'U32.or(U32.shrn(hi, %dn), U32.shln(lo, %dn))' % (m, 32 - m))


def shr(n):
    return ('U32.shrn(hi, %dn)' % n, 'U32.or(U32.shrn(lo, %dn), U32.shln(hi, %dn))' % (n, 32 - n))


def fused(name, parts, doc):
    hi = 'U32.xor(U32.xor(%s, %s), %s)' % tuple(p[0] for p in parts)
    lo = 'U32.xor(U32.xor(%s, %s), %s)' % tuple(p[1] for p in parts)
    return '''# %s
def %s(x: T.Lane) -> T.Lane:
  match x:
    case T.W{+hi, +lo}:
      T.W{%s,
        %s}
''' % (doc, name, hi, lo)


