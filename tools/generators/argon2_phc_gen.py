def nat_cases(var, n, leaf, absurd):
    """match on a Nat below n: one leaf per value, the rest absurd."""
    s = '  match %s:\n' % var
    for k in range(n):
        s += '    case %dn:\n      %s\n' % (k, leaf(k))
    s += '    case %dn+r:\n      %s\n' % (n, absurd)
    return s


class Goal:
    """A chain of rewrites % e : P on the left side of {lhs == rhs : T}."""

    def __init__(self, lhs, rhs, ty, ind='  '):
        self.lhs, self.rhs, self.ty, self.ind, self.out = lhs, rhs, ty, ind, ''

    def rw(self, old, new, e):
        assert old in self.lhs, (old, self.lhs)
        p = self.lhs.replace(old, '_')
        self.out += '%s%%%s : {%s == %s : %s}\n' % (self.ind, e, p, self.rhs, self.ty)
        self.lhs = self.lhs.replace(old, new)

    def set(self, lhs):
        self.lhs = lhs

    def done(self, last='{==}'):
        return self.out + self.ind + last + '\n'


def sym(ty, a, b, e):
    return 'Equal.sym(%s, %s, %s, %s)' % (ty, a, b, e)


def fix_tn(s):
    out = []
    for line in s.split('\n'):
        m = re.match(r'  %tn\((.*), (NR\.dm_lt\(.*\)|t3_lt\(x, h\))\) : \{(.*)$', line)
        if m:
            e, pr, rest = m.groups()
            line = '  %%Equal.sym(Nat, U32.to_nat(U32.from_nat(%s)), %s, tn(%s, %s)) : {%s' % (e, e, e, pr, rest)
        out.append(line)
    return '\n'.join(out)


