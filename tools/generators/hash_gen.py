def incremental():
    out = [HEADER]
    for a in ALGS:
        x, S, Bn, q0 = a['x'], a['S'], a['B'], a['q']
        B = bs(Bn)
        PT = 'H.' + a['ST']
        fst = lambda p: 'st%s(%s)' % (x, p)
        snd = lambda p: 'buf%s(%s)' % (x, p)
        G = a['G']
        app = lambda u, v: 'List.append(&2, U32, %s, %s)' % (u, v)
        shorts = ''.join('        case %s:\n          {==}\n' % (' <> '.join(B[:k] + ['Nil{}'])) for k in range(Bn))
        step = a['step']()
        if x == '256':
            ab = 'H.absorb%s(p, H.read%s_0(rest), rest, q, fast)' % (x, x)
            full = ('          +fast = %s\n          %%SC.fips16_correct(%s, q, s) :\n            {%s == %s : %s}\n          absorb%s_inv(p, rest, q, fast, z)'
                    % (step, ', '.join(packs4('C256', 64)), G(app('rest', 'z'), '_'),
                       G(app(snd(ab), 'z'), fst(ab)), S, x))
        else:
            full = '          absorb%s_inv(p, rest, q, %s, z)' % (x, step)
        d = dict(a, PT=PT, pat=' <> '.join(B), full=full, shorts=shorts, q0=q0,
                 newname={'256': 'sha256', '512': 'sha512', '3': 'sha3_256'}[x],
                 sndst=snd('st'), sndst2=snd('st2'),
                 Gbz=G(app('bytes', 'z'), 's'),
                 Gab=G(app(snd('H.absorb%s(fuel, H.read%s_0(bytes), bytes, q, s)' % (x, x)), 'z'), fst('H.absorb%s(fuel, H.read%s_0(bytes), bytes, q, s)' % (x, x))),
                 Gstep_l=G(app(app(snd('st'), 'xs'), 'z'), fst('st')),
                 Gstep_r=G(app(snd('H.step%s(st, xs, q)' % x), 'z'), fst('H.step%s(st, xs, q)' % x)),
                 Gfold_l=G(app(app(snd('st'), 'List.concat(&2, U32, cs)'), 'z'), fst('st')),
                 Gfold_r=G(app(snd('fold%s(cs, q, st)' % x), 'z'), fst('fold%s(cs, q, st)' % x)),
                 Gnil_l=G(app(app(snd('st'), 'Nil{}'), 'z'), fst('st')),
                 Gnil_r=G(app('_', 'z'), fst('st')),
                 c0=G(app(app(snd('st'), app('c', 'm')), 'z'), fst('st')),
                 c2=G(app(app(snd('st'), 'c'), app('m', 'z')), fst('st')),
                 c3=G(app(snd('st2'), app('m', 'z')), fst('st2')),
                 c3b=G(app(app(snd('st2'), 'm'), 'z'), fst('st2')),
                 c4=G(app(snd('fold%s(ct, q, st2)' % x), 'z'), fst('fold%s(ct, q, st2)' % x)),
                 Gt=G('t', fst('st')), Gt2=G('t', fst('st2')),
                 a0=app(app(snd('st'), app('c', 'm')), 'z'),
                 a1=app(app(app(snd('st'), 'c'), 'm'), 'z'),
                 a2=app(app(snd('st'), 'c'), app('m', 'z')),
                 aa0=app(snd('st'), app('c', 'm')), aa1=app(app(snd('st'), 'c'), 'm'),
                 appsc=app(snd('st'), 'c'),
                 b0=app(snd('st2'), app('m', 'z')), b1=app(app(snd('st2'), 'm'), 'z'),
                 Ffin=a['F'](G(app(snd('st'), '%s(len)' % a['suffix']), fst('st'))),
                 Fone=a['F'](G(app('List.concat(&2, U32, cs)', '%s(List.length(&2, U32, List.concat(&2, U32, cs)))' % a['suffix']), a['init'], q0)),
                 Fs=a['F']('t'),
                 Fq=a['F'](G(app(snd('qs'), '%s(List.length(&2, U32, m))' % a['suffix']), fst('qs'), q0)),
                 Gq=G(app(snd('qs'), '%s(List.length(&2, U32, m))' % a['suffix']), fst('qs'), q0),
                 Gm=G(app('m', '%s(List.length(&2, U32, m))' % a['suffix']), a['init'], q0),
                 sfx=a['suffix'])
        out.append(TEMPLATE % d)
    return ''.join(out)


def main():
    (ROOT / 'src/crypto/hash.bend').write_text(facade())
    (ROOT / 'proofs/crypto/hash').mkdir(parents=True, exist_ok=True)
    (ROOT / 'proofs/crypto/hash/incremental.bend').write_text(incremental())


if __name__ == '__main__':
    main()
