"""Generate src/crypto/hash.bend and proofs/crypto/hash/incremental.bend.

  python3 tools/generators/hash_gen.py

The facade's block readers (64, 128 and 136 bytes per block) and the
per-algorithm proofs of the incremental hasher are one template instantiated
three times, with the short-tail case enumerations of the proofs.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def bs(n):
    return ['b%d' % i for i in range(n)]


def packs4(prefix, n):
    b = bs(n)
    return ['%s.pack(%s)' % (prefix, ', '.join(b[i:i + 4])) for i in range(0, n, 4)]


def lanes8(prefix, T, n):
    p = packs4(prefix, n)
    return ['%s.W{%s, %s}' % (T, p[i], p[i + 1]) for i in range(0, len(p), 2)]


