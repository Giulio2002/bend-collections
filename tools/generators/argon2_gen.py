#!/usr/bin/env python3
"""Generates the repetitive Argon2 Bend files (implementation and proofs).

  python3 tools/generators/argon2_gen.py

Writes src/crypto/argon2/{types,blamka,sub}.bend and the generated proof
files proofs/crypto/argon2/{blamka,rows,cols,sub}.bend. Written by hand:
the rest of src/crypto/argon2/, spec/crypto/argon2/ and
proofs/crypto/argon2/.

A block is 128 64-bit lanes, as eight rows T.V{v0..v15} of sixteen lanes
(lane n is row n / 16, position n mod 16), each lane T.W{lo, hi}.
"""
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SRC = os.path.join(ROOT, 'src/crypto/argon2')
PRF = os.path.join(ROOT, 'proofs/crypto/argon2')
HEADER = '# Generated by tools/generators/argon2_gen.py; do not edit by hand.\n'

# RFC 9106 section 3.6: the eight GB applications of the permutation P.
STEPS = [(0, 4, 8, 12), (1, 5, 9, 13), (2, 6, 10, 14), (3, 7, 11, 15),
         (0, 5, 10, 15), (1, 6, 11, 12), (2, 7, 8, 13), (3, 4, 9, 14)]


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        f.write(text)


def csv(xs):
    return ','.join(xs)


def st(xs):
    return 'T.V{' + csv(xs) + '}'


def blk(rows):
    return 'A.B{' + csv(rows) + '}'


def lanes(p='l', n=128):
    return ['%s%d' % (p, i) for i in range(n)]


def block_of_lanes(ls):
    return blk([st(ls[16 * r:16 * r + 16]) for r in range(8)])


def col_lanes(i):
    """Lane numbers of column i, in state order: 2i, 2i+1, 2i+16, 2i+17, ..."""
    out = []
    for k in range(8):
        out += [16 * k + 2 * i, 16 * k + 2 * i + 1]
    return out


# ---------------------------------------------------------------- implementation

def types():
    return (HEADER + 'import Base\nimport ../blake/blake2b/types.bend as T\n\n'
            '# A 1024-byte block: 128 64-bit lanes as eight rows of sixteen\n'
            '# (lane n is row n / 16, position n mod 16).\n'
            'type Block is Data:\n  B{' + ', '.join('r%d: T.State' % i for i in range(8)) + '}\n')


def step_fns(k, a, b, c, d):
    """Step k of P: GB on positions a, b, c, d of the state."""
    others = [i for i in range(16) if i not in (a, b, c, d)]
    xs = ['x%d' % i for i in range(16)]
    s = ''
    # put_k: write the four results back
    params = ', '.join('x%d: T.Lane' % i for i in others)
    out = []
    for i in range(16):
        if i == a:
            out.append('ya')
        elif i == b:
            out.append('yb')
        elif i == c:
            out.append('yc')
        elif i == d:
            out.append('yd')
        else:
            out.append('x%d' % i)
    s += 'def put%d(q: T.Quad, %s) -> T.State:\n' % (k, params)
    s += '  match q:\n    case T.Q{ya,yb,yc,yd}:\n'
    s += '      ' + st(out) + '\n\n'
    s += '# GB on positions %d, %d, %d, %d.\n' % (a, b, c, d)
    s += 'def step%d(v: T.State) -> T.State:\n' % k
    s += '  match v:\n    case ' + st(xs) + ':\n'
    s += '      put%d(gb(x%d,x%d,x%d,x%d),%s)\n\n' % (k, a, b, c, d, csv('x%d' % i for i in others))
    return s


def blamka():
    s = HEADER
    s += ('import Base\n'
          'import ../../math/w64.bend as X\n'
          'import ../blake/blake2b/types.bend as T\n'
          'import ../blake/blake2b/lane.bend as L\n'
          'import ./types.bend as A\n\n')
    s += ('# The low half of a lane (trunc in RFC 9106).\n'
          'def lo(x: T.Lane) -> U32:\n  match x:\n    case T.W{l,h}: l\n\n'
          '# The full 64-bit product of two U32 (src/math/w64.bend, proved).\n'
          'def prod(+a: U32, +b: U32) -> T.Lane:\n'
          '  +m = X.mul32(a,b)\n'
          '  T.W{X.lo(m),X.hi(m)}\n\n'
          '# fBlaMka(x, y) = x + y + 2 * trunc(x) * trunc(y) mod 2^64 (RFC 9106 section 3.6).\n'
          'def bla(+x: T.Lane, +y: T.Lane) -> T.Lane:\n'
          '  +p = prod(lo(x),lo(y))\n'
          '  L.add(L.add(x,y),L.add(p,p))\n\n')
    s += ('# GB (RFC 9106 section 3.6), one assignment pair per function.\n'
          'def gb4(+a2: T.Lane, +b1: T.Lane, +c2: T.Lane, +d2: T.Lane) -> T.Quad:\n'
          '  T.Q{a2,L.rot63(L.xor(b1,c2)),c2,d2}\n\n'
          'def gb3(+a2: T.Lane, +b1: T.Lane, +c1: T.Lane, +d1: T.Lane) -> T.Quad:\n'
          '  +d2 = L.rot16(L.xor(d1,a2))\n'
          '  gb4(a2,b1,bla(c1,d2),d2)\n\n'
          'def gb2(+a1: T.Lane, +b: T.Lane, +c1: T.Lane, +d1: T.Lane) -> T.Quad:\n'
          '  +b1 = L.rot24(L.xor(b,c1))\n'
          '  gb3(bla(a1,b1),b1,c1,d1)\n\n'
          'def gb1(+a1: T.Lane, +b: T.Lane, +c: T.Lane, +d: T.Lane) -> T.Quad:\n'
          '  +d1 = L.rot32(L.xor(d,a1))\n'
          '  gb2(a1,b,bla(c,d1),d1)\n\n'
          'def gb(+a: T.Lane, +b: T.Lane, +c: T.Lane, +d: T.Lane) -> T.Quad:\n'
          '  gb1(bla(a,b),b,c,d)\n\n')
    for k, (a, b, c, d) in enumerate(STEPS):
        s += step_fns(k, a, b, c, d)
    s += ('# The permutation P on sixteen lanes.\n'
          'def p(v: T.State) -> T.State:\n'
          '  step7(step6(step5(step4(step3(step2(step1(step0(v))))))))\n\n')
    # rows
    s += ('# P on each row: lanes 16i .. 16i+15.\n'
          'def rows(b: A.Block) -> A.Block:\n'
          '  match b:\n    case A.B{r0,r1,r2,r3,r4,r5,r6,r7}:\n'
          '      A.B{p(r0),p(r1),p(r2),p(r3),p(r4),p(r5),p(r6),p(r7)}\n\n')
    # cols
    L = lanes()
    cs = ['c%d' % i for i in range(8)]
    ys = [['y%d_%d' % (i, j) for j in range(16)] for i in range(8)]
    s += '# The eight permuted columns back into rows: column i holds lanes 2i, 2i+1 of every row.\n'
    s += 'def untr(%s) -> A.Block:\n' % ', '.join('%s: T.State' % c for c in cs)
    s += '  match %s:\n' % ' '.join(cs)
    s += '    case %s:\n' % ' '.join(st(y) for y in ys)
    rows = []
    for k in range(8):
        row = []
        for i in range(8):
            row += [ys[i][2 * k], ys[i][2 * k + 1]]
        rows.append(st(row))
    s += '      ' + blk(rows) + '\n\n'
    s += ('# P on each column: lanes 2i, 2i+1, 2i+16, 2i+17, .., 2i+112, 2i+113.\n'
          'def cols(b: A.Block) -> A.Block:\n'
          '  match b:\n    case ' + block_of_lanes(L) + ':\n'
          '      untr(' + csv('p(' + st(['l%d' % n for n in col_lanes(i)]) + ')' for i in range(8)) + ')\n\n')
    # xor
    xs = lanes('x')
    zs = lanes('y')
    s += ('# Lane-wise XOR of two blocks.\n'
          'def xor(x: A.Block, y: A.Block) -> A.Block:\n'
          '  match x y:\n    case ' + block_of_lanes(xs) + ' ' + block_of_lanes(zs) + ':\n'
          '      ' + block_of_lanes(['L.xor(x%d,y%d)' % (i, i) for i in range(128)]) + '\n\n')
    s += ('# G(X, Y) = P(R) XOR R with R = X XOR Y, P on the rows then the columns\n'
          '# (RFC 9106 section 3.5).\n'
          'def fin(+r: A.Block) -> A.Block:\n'
          '  xor(cols(rows(r)),r)\n\n'
          'def compress(x: A.Block, y: A.Block) -> A.Block:\n'
          '  fin(xor(x,y))\n\n'
          '# Version 0x13 passes after the first: G(X, Y) XOR the block being overwritten.\n'
          'def compress_xor(x: A.Block, y: A.Block, old: A.Block) -> A.Block:\n'
          '  xor(compress(x,y),old)\n\n'
          '# The all-zero block.\n'
          'def zero() -> A.Block:\n'
          '  ' + block_of_lanes(['T.W{0,0}'] * 128) + '\n')
    return s


def sub():
    """Blocks as the 256 leaves of a depth-8 subtree of the packed memory array."""
    s = HEADER
    s += ('import Base\n'
          'import ../blake/blake2b/types.bend as T\n'
          'import ./types.bend as A\n\n')
    # build
    def tree(ws):
        if len(ws) == 1:
            return 'ALeaf{%s}' % ws[0]
        h = len(ws) // 2
        return 'ANode{%s,%s}' % (tree(ws[:h]), tree(ws[h:]))
    ws = []
    for n in range(128):
        ws += ['l%d' % n, 'h%d' % n]
    s += ('# The block as a perfect depth-8 array of 256 words: lane n is words 2n (low)\n'
          '# and 2n+1 (high).\n'
          'def build(b: A.Block) -> Array<U32>:\n'
          '  match b:\n    case ' + block_of_lanes(['T.W{l%d,h%d}' % (n, n) for n in range(128)]) + ':\n'
          '      ' + tree(ws) + '\n\n')
    # leaves, one function per level (no mutual recursion)
    s += '# The words of a depth-k array in order, prepended to acc; the array is handed back.\n'
    s += ('def leaves0(t: Array<U32>, acc: List<&2,U32>) -> Array<U32> & List<&2,U32>:\n'
          '  match t:\n'
          '    case ALeaf{+x}: (ALeaf{x},x <> acc)\n'
          '    case ANode{l,r}: (ANode{l,r},acc)\n\n')
    for k in range(1, 9):
        s += ('def leaves%d_b(r: Array<U32>, p: Array<U32> & List<&2,U32>) -> Array<U32> & List<&2,U32>:\n'
              '  (l,acc) = p\n'
              '  (ANode{l,r},acc)\n\n' % k)
        s += ('def leaves%d_a(l: Array<U32>, p: Array<U32> & List<&2,U32>) -> Array<U32> & List<&2,U32>:\n'
              '  (r,acc) = p\n'
              '  leaves%d_b(r,leaves%d(l,acc))\n\n' % (k, k, k - 1))
        s += ('def leaves%d(t: Array<U32>, acc: List<&2,U32>) -> Array<U32> & List<&2,U32>:\n'
              '  match t:\n'
              '    case ALeaf{+x}: (ALeaf{x},acc)\n'
              '    case ANode{l,r}: leaves%d_a(l,leaves%d(r,acc))\n\n' % (k, k, k - 1))
    # row of words
    w = ['w%d' % i for i in range(32)]
    s += ('# Sixteen lanes from 32 words, and the words left over.\n'
          'def row(ws: List<&2,U32>) -> T.State & List<&2,U32>:\n'
          '  match ws:\n'
          '    case ' + ' <> '.join(w) + ' <> rest:\n'
          '      (' + st(['T.W{w%d,w%d}' % (2 * i, 2 * i + 1) for i in range(16)]) + ',rest)\n'
          '    case _: (' + st(['T.W{0,0}'] * 16) + ',Nil{})\n\n')
    for r in reversed(range(8)):
        prev = ''.join('r%d: T.State, ' % i for i in range(r))
        s += 'def rows8_%d(%sp: T.State & List<&2,U32>) -> A.Block:\n' % (r, prev)
        s += '  (r%d,ws) = p\n' % r
        if r < 7:
            s += '  rows8_%d(%srow(ws))\n\n' % (r + 1, ''.join('r%d,' % i for i in range(r + 1)))
        else:
            s += '  A.B{r0,r1,r2,r3,r4,r5,r6,r7}\n\n'
    s += '# Eight rows from 256 words.\n'
    s += 'def rows8(ws: List<&2,U32>) -> A.Block:\n  rows8_0(row(ws))\n\n'
    s += ('def read_fin(p: Array<U32> & List<&2,U32>) -> Array<U32> & A.Block:\n'
          '  (t,ws) = p\n'
          '  (t,rows8(ws))\n\n'
          '# The block stored in a depth-8 subtree; the subtree is handed back.\n'
          'def read(t: Array<U32>) -> Array<U32> & A.Block:\n'
          '  read_fin(leaves8(t,Nil{}))\n')
    return s


def main():
    write(os.path.join(SRC, 'types.bend'), types())
    write(os.path.join(SRC, 'blamka.bend'), blamka())
    write(os.path.join(SRC, 'sub.bend'), sub())


if __name__ == '__main__':
    main()
