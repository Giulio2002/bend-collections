#!/usr/bin/env python3
"""Emit the repetitive ChaCha8Rand Bend sources (implementation and proofs).

  python3 tools/generators/chacha8rand_gen.py

Writes, relative to the repository root:
  src/math/random/chacha8/block.bend          the unrolled ChaCha8 double round,
                                              block and four-block group
  proofs/math/random/chacha8/rounds.bend      the double round against the
                                              list-based specification

The specification (spec/math/random/chacha8rand.bend), the source
(src/math/random/chacha8.bend) and the other proofs are hand-written.
"""
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SRC = os.path.join(ROOT, 'src/math/random/chacha8')
PRF = os.path.join(ROOT, 'proofs/math/random/chacha8')

# "expand 32-byte k" as four little-endian words
SIGMA = [0x61707865, 0x3320646E, 0x79622D32, 0x6B206574]
# quarter rounds of one double round (RFC 8439 section 2.3): columns, diagonals
QRS = [(0, 4, 8, 12), (1, 5, 9, 13), (2, 6, 10, 14), (3, 7, 11, 15),
       (0, 5, 10, 15), (1, 6, 11, 12), (2, 7, 8, 13), (3, 4, 9, 14)]


def ws(p, n, plus=''):
    return ','.join('%s%s%d' % (plus, p, i) for i in range(n))


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        f.write(text)
    print('wrote', os.path.relpath(path, ROOT))


def rotl(x, n):
    return 'U32.or(U32.shln(%s,%dn),U32.shrn(%s,%dn))' % (x, n, x, 32 - n)


def gen_block():
    L = ['# Generated by tools/generators/chacha8rand_gen.py; do not edit.',
         '# The ChaCha8 core of ChaCha8Rand (C2SP chacha8rand; Go\'s',
         '# internal/chacha8rand block_generic). One double round is fully unrolled',
         '# (four column and four diagonal quarter rounds, RFC 8439 section 2.1-2.3,',
         '# constant rotations); a block is four double rounds (eight rounds). As',
         '# C2SP specifies, only the key words 4..11 are added back after the rounds:',
         '# the constants and the counter are not (the standard ChaCha output minus',
         '# them). A group is four consecutive blocks interleaved word by word, read',
         '# as 32 little-endian 64-bit words: word 2w of the group is word w of the',
         '# first block (low half) and of the second (high half), word 2w + 1 the',
         '# same for the third and fourth block.',
         '#',
         '# Proved equal to spec/math/random/chacha8rand.bend for every key and',
         '# counter (proofs/math/random/chacha8/).',
         'import Base',
         'import ../../u64.bend as W',
         '',
         '# the 256-bit key as eight little-endian words',
         'type Key is Data:',
         '  K{%s}' % ', '.join('k%d: U32' % i for i in range(8)),
         '',
         '# the ChaCha state x[0..15]',
         'type Vector is Data:',
         '  V{%s}' % ', '.join('v%d: U32' % i for i in range(16)),
         '',
         '# the initial state: constants, key, 32-bit block counter, zero nonce',
         'def init(k: Key, +ctr: U32) -> Vector:',
         '  match k:',
         '    case K{%s}:' % ws('k', 8),
         '      V{%s,%s,ctr,0,0,0}' % (','.join(str(c) for c in SIGMA), ws('k', 8)),
         '',
         '# one double round: four column quarter rounds, then four diagonal ones',
         'def dr(v: Vector) -> Vector:',
         '  match v:',
         '    case V{%s}:' % ws('a', 16, '+')]
    cur = ['a%d' % i for i in range(16)]
    for qi, (a, b, c, d) in enumerate(QRS):
        va, vb, vc, vd = cur[a], cur[b], cur[c], cur[d]
        n = lambda s: 'q%d%s' % (qi, s)

        def rot(dst, p, q, r):
            L.append('      +%sx = U32.xor(%s,%s)' % (dst, p, q))
            L.append('      +%s = %s' % (dst, rotl(dst + 'x', r)))
        L.append('      +%s = U32.add(%s,%s)' % (n('a1'), va, vb))
        rot(n('d1'), vd, n('a1'), 16)
        L.append('      +%s = U32.add(%s,%s)' % (n('c1'), vc, n('d1')))
        rot(n('b1'), vb, n('c1'), 12)
        L.append('      +%s = U32.add(%s,%s)' % (n('a2'), n('a1'), n('b1')))
        rot(n('d2'), n('d1'), n('a2'), 8)
        L.append('      +%s = U32.add(%s,%s)' % (n('c2'), n('c1'), n('d2')))
        rot(n('b2'), n('b1'), n('c2'), 7)
        cur[a], cur[b], cur[c], cur[d] = n('a2'), n('b2'), n('c2'), n('d2')
    L.append('      V{%s}' % ','.join(cur))
    L += ['',
          '# the key words added back to words 4..11',
          'def finish(k: Key, v: Vector) -> Vector:',
          '  match k v:',
          '    case K{%s} V{%s}:' % (ws('k', 8), ws('v', 16)),
          '      V{v0,v1,v2,v3,%s,v12,v13,v14,v15}' % ','.join('U32.add(v%d,k%d)' % (i + 4, i) for i in range(8)),
          '',
          '# the ChaCha8Rand block with counter ctr: eight rounds',
          'def block(+k: Key, +ctr: U32) -> Vector:',
          '  finish(k,dr(dr(dr(dr(init(k,ctr))))))',
          '',
          '# four blocks interleaved word by word, as 32 little-endian 64-bit words',
          'def interleave(a: Vector, b: Vector, c: Vector, d: Vector) -> List<&2,W.U64>:',
          '  match a b c d:',
          '    case V{%s} V{%s} V{%s} V{%s}:' % (ws('a', 16), ws('b', 16), ws('c', 16), ws('d', 16)),
          '      [%s]' % ','.join('W.U64{a%d,b%d},W.U64{c%d,d%d}' % (w, w, w, w) for w in range(16)),
          '',
          '# the group of the blocks ctr, ctr + 1, ctr + 2, ctr + 3',
          'def group(+k: Key, +ctr: U32) -> List<&2,W.U64>:',
          '  interleave(block(k,ctr),block(k,U32.add(ctr,1)),block(k,U32.add(ctr,2)),block(k,U32.add(ctr,3)))',
          '']
    write(os.path.join(SRC, 'block.bend'), '\n'.join(L))


def gen_rounds_proof():
    V = ws('a', 16)
    L = ['# Generated by tools/generators/chacha8rand_gen.py; do not edit.',
         '# The unrolled ChaCha8 pieces of src/math/random/chacha8/block.bend against',
         '# the list-based RFC 8439 / C2SP specification spec/math/random/chacha8rand.bend,',
         '# for every state and key: one double round (both sides symbolic in the',
         '# sixteen words, so the checker compares one double round at a time), the',
         '# initial state, the final additions with C2SP\'s subtractions, and the',
         '# four-block interleaving.',
         'import Base',
         'import ../../../../src/math/u64.bend as W',
         'import ../../../../src/math/random/chacha8/block.bend as B',
         'import ../../../../spec/math/random/chacha8rand.bend as S',
         'import ../../../lib/u32alg.bend as A',
         '',
         '# the state as the RFC list x[0..15]; like S.key_list on a key, it is stuck',
         '# on an abstract state, so the checker never unfolds rounds of symbolic',
         '# words it does not have to compare',
         ]
    L += ['def vec(v: B.Vector) -> List<&2,U32>:', '  match v:', '    case B.V{%s}: [%s]' % (V, V), '']
    K = ws('k', 8)
    L += ['# one double round is RFC 8439\'s inner_block',
          'def dr_correct(+v: B.Vector) -> {vec(B.dr(v)) == S.double_round(vec(v)) : List<&2,U32>}:',
          '  match v:',
          '    case B.V{%s}: {==}' % V, '',
          'def init_correct(+k: B.Key, +ctr: U32) -> {vec(B.init(k,ctr)) == S.initial(S.key_list(k),ctr) : List<&2,U32>}:',
          '  match k:',
          '    case B.K{%s}: {==}' % K, '',
          '# x + c - c = x',
          'def cancel(+x: U32, +c: U32) -> {U32.sub(U32.add(x,c),c) == x : U32}:',
          '  %A.comm(c,x) : {U32.sub(_,c) == x : U32}',
          '  A.add_sub(c,x)', '']
    # finish_correct: rewrite words 0..3 and 12 (cancel) and 13..15 (add_zero)
    C = [0x61707865, 0x3320646E, 0x79622D32, 0x6B206574]
    lhs = ['v0', 'v1', 'v2', 'v3'] + ['U32.add(v%d,k%d)' % (i + 4, i) for i in range(8)] + ['v12', 'v13', 'v14', 'v15']
    cplx = ['U32.sub(U32.add(v%d,%d),%d)' % (i, C[i], C[i]) for i in range(4)] + lhs[4:12] + \
           ['U32.sub(U32.add(v12,ctr),ctr)', 'U32.add(v13,0)', 'U32.add(v14,0)', 'U32.add(v15,0)']
    L += ['# the key words added back, C2SP\'s subtractions of the constants and the',
          '# counter, and the zero nonce words: the words the implementation keeps',
          'def finish_correct(+k: B.Key, +v: B.Vector, +ctr: U32) -> {vec(B.finish(k,v)) == S.subtract(S.add_words(vec(v),vec(B.init(k,ctr))),ctr) : List<&2,U32>}:',
          '  match k v:',
          '    case B.K{%s} B.V{%s}:' % (K, ws('v', 16))]
    cur = cplx[:]
    for i in [0, 1, 2, 3, 12, 13, 14, 15]:
        if i < 4:
            e = 'Equal.sym(U32,%s,v%d,cancel(v%d,%d))' % (cplx[i], i, i, C[i])
        elif i == 12:
            e = 'Equal.sym(U32,%s,v12,cancel(v12,ctr))' % cplx[i]
        else:
            e = 'Equal.sym(U32,%s,v%d,A.add_zero(v%d))' % (cplx[i], i, i)
        hole = cur[:]
        hole[i] = '_'
        L.append('      %%%s : {[%s] == [%s] : List<&2,U32>}' % (e, ','.join(lhs), ','.join(hole)))
        cur[i] = lhs[i]
    L += ['      {==}', '']
    L += ['# the interleaving is C2SP\'s permutation read as little-endian 64-bit words',
          'def interleave_correct(+a: B.Vector, +b: B.Vector, +c: B.Vector, +d: B.Vector) -> {B.interleave(a,b,c,d) == S.words64(S.interleave(16n,0n,vec(a),vec(b),vec(c),vec(d))) : List<&2,W.U64>}:',
          '  match a b c d:',
          '    case B.V{%s} B.V{%s} B.V{%s} B.V{%s}: {==}' % (ws('a', 16), ws('b', 16), ws('c', 16), ws('d', 16)), '']
    write(os.path.join(PRF, 'rounds.bend'), '\n'.join(L))


def main():
    gen_block()
    gen_rounds_proof()


if __name__ == '__main__':
    main()
