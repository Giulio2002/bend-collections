#!/usr/bin/env python3
"""Generate src/crypto/sha3/core.bend and proofs/crypto/sha3/conformance.bend.

  python3 tools/generators/sha3_gen.py

The 17-lane block patterns and the proof's case enumerations are mechanical.
The specification spec/crypto/sha3.bend is written by hand.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
R = 17                      # rate in lanes (136 bytes)
LS = ['l%d' % i for i in range(R)]
AS = ['a%d' % i for i in range(25)]


def core():
    inj = ', '.join('L.xor(a%d, l%d)' % (i, i) for i in range(R)) + ', ' + ', '.join(AS[R:])
    return '''# Generated by tools/generators/sha3_gen.py; do not edit by hand.
import Base
import ../keccak/types.bend as T
import ../keccak/lane.bend as L
import ../keccak/permutation.bend as P

# SHA3-256 (FIPS 202) on byte lists, on the Keccak-f[1600] of
# src/crypto/keccak/permutation.bend (two rounds per step, proved equal to
# FIPS 202's permutation in proofs/crypto/keccak/permutation.bend). The
# message is padded (0x06 .. 0x80), read as little-endian lanes, and absorbed
# 17 lanes (136 bytes) at a time; the digest is the first four lanes.
# Proved equal to spec/crypto/sha3.bend in proofs/crypto/sha3/.

def pack(a: U32, b: U32, c: U32, d: U32) -> U32:
  U32.or(U32.or(U32.or(U32.and(a, 255), U32.shln(U32.and(b, 255), 8n)),
    U32.shln(U32.and(c, 255), 16n)), U32.shln(U32.and(d, 255), 24n))

def lanes(bytes: List<&2, U32>) -> List<&2, T.Lane>:
  match bytes:
    case a <> b <> c <> d <> e <> f <> g <> h <> rest:
      T.W{pack(a, b, c, d), pack(e, f, g, h)} <> lanes(rest)
    case _:
      Nil{}

# 0x06, zeros, 0x80 up to the end of the block (0x86 when one byte is left).
def tail(q: Nat) -> List<&2, U32>:
  match q:
    case 0n:
      Nil{}
    case 1n:
      [134]
    case 2n+k:
      6 <> List.append(&2, U32, List.replicate(U32, k, 0), [128])

def suffix(+n: Nat) -> List<&2, U32>:
  tail(Nat.sub(136n, Nat.mod(n, 136n)))

def zero() -> T.State:
  T.S{%(zeros)s}

# XOR one block into the leading 17 lanes.
def inject(s: T.State, %(ldecl)s) -> T.State:
  match s:
    case T.S{%(A)s}:
      T.S{%(inj)s}

# Absorb every whole block of 17 lanes with the given round count (24).
def absorb(ls: List<&2, T.Lane>, +rounds: Nat, s: T.State) -> T.State:
  match ls:
    case %(LP)s <> rest:
      absorb(rest, rounds, P.rounds(rounds, 0n, inject(s, %(L)s)))
    case _:
      s

def le_bytes(+x: U32, tail: List<&2, U32>) -> List<&2, U32>:
  U32.and(x, 255) <> U32.and(U32.shrn(x, 8n), 255) <> U32.and(U32.shrn(x, 16n), 255) <> U32.shrn(x, 24n) <> tail

# The 32-byte digest: lanes 0..3, little-endian.
def digest_bytes(s: T.State) -> List<&2, U32>:
  match s:
    case T.S{T.W{l0, h0}, T.W{l1, h1}, T.W{l2, h2}, T.W{l3, h3}, %(rest4)s}:
      le_bytes(l0, le_bytes(h0, le_bytes(l1, le_bytes(h1, le_bytes(l2, le_bytes(h2, le_bytes(l3, le_bytes(h3, Nil{}))))))))

def hash_padded(bytes: List<&2, U32>, +rounds: Nat) -> List<&2, U32>:
  digest_bytes(absorb(lanes(bytes), rounds, zero()))

def keccak(+bytes: List<&2, U32>, +rounds: Nat) -> List<&2, U32>:
  hash_padded(List.append(&2, U32, bytes, suffix(List.length(&2, U32, bytes))), rounds)

def sha3_256(bytes: List<&2, U32>) -> List<&2, U32>:
  keccak(bytes, 24n)
''' % dict(zeros=', '.join(['T.W{0, 0}'] * 25), ldecl=', '.join('%s: T.Lane' % l for l in LS),
           A=', '.join(AS), inj=inj, LP=' <> '.join(LS), L=', '.join(LS), rest4=', '.join(AS[4:]))


def conformance():
    sp = 'T.S{%s}' % ', '.join('T.W{p%d, q%d}' % (i, i) for i in range(25))
    lp = ' '.join('T.W{u%d, v%d}' % (i, i) for i in range(R))
    B = ['b%d' % i for i in range(8)]
    short_bytes = ''.join('    case %s:\n      {==}\n' % (' <> '.join(B[:k] + ['Nil{}'])) for k in range(8))
    short_lanes = ''.join('    case %s:\n      {==}\n' % (' <> '.join(LS[:k] + ['Nil{}'])) for k in range(R))
    lanes_for = ''.join('  for +%s: T.Lane\n' % l for l in LS)
    L = ', '.join(LS)
    return '''# Generated by tools/generators/sha3_gen.py; do not edit by hand.
import Base
import ../../../src/crypto/keccak/types.bend as T
import ../../../src/crypto/keccak/permutation.bend as P
import ../../../src/crypto/sha3/core.bend as C
import ../../../spec/crypto/sha3.bend as F
import ../../../spec/crypto/keccak/permutation.bend as K
import ../keccak/permutation.bend as KP

# src/crypto/sha3/core.bend refines spec/crypto/sha3.bend: the block XOR is
# equal after opening every lane, the permutation is the Keccak package's
# proved one (KP.rounds_correct, for every round count), and the absorbing,
# the parsing, the padding and the squeeze follow by induction or unfolding.
# The round count stays a variable until the end (24 is never unfolded).

law inject_correct:
  for +s: T.State
%(lanes_for)s  {C.inject(s, %(L)s) == F.of_lanes(F.xor_lanes(F.to_lanes(s), [%(L)s])) : T.State}

def inject_correct(s, %(L)s):
  match s %(Lsp)s:
    case %(sp)s %(lp)s:
      {==}

law absorb_correct:
  for +ls: List<&2, T.Lane>
  for +rounds: Nat
  for +s: T.State
  {C.absorb(ls, rounds, s) == F.absorb(ls, rounds, s) : T.State}

def absorb_correct(ls, rounds, s):
  match ls:
    case %(LP)s <> rest:
      +x = F.of_lanes(F.xor_lanes(F.to_lanes(s), [%(L)s]))
      %%inject_correct(s, %(L)s) :
        {C.absorb(%(LP)s <> rest, rounds, s) == F.absorb(rest, rounds, K.rounds(rounds, 0n, _)) : T.State}
      %%KP.rounds_correct(rounds, 0n, C.inject(s, %(L)s)) :
        {C.absorb(%(LP)s <> rest, rounds, s) == F.absorb(rest, rounds, _) : T.State}
      absorb_correct(rest, rounds, P.rounds(rounds, 0n, C.inject(s, %(L)s)))
%(short_lanes)s
law lanes_correct:
  for +bytes: List<&2, U32>
  {C.lanes(bytes) == F.lanes(bytes) : List<&2, T.Lane>}

def lanes_correct(bytes):
  match bytes:
    case %(B8)s <> rest:
      %%lanes_correct(rest) :
        {C.lanes(%(B8)s <> rest) == T.W{F.le32(b0, b1, b2, b3), F.le32(b4, b5, b6, b7)} <> _ : List<&2, T.Lane>}
      {==}
%(short_bytes)s
law tail_correct:
  for +q: Nat
  {C.tail(q) == F.padding_bytes(q) : List<&2, U32>}

def tail_correct(q):
  match q:
    case 0n:
      {==}
    case 1n:
      {==}
    case 2n+k:
      {==}

law suffix_correct:
  for +n: Nat
  {C.suffix(n) == F.padding(n) : List<&2, U32>}

def suffix_correct(n):
  tail_correct(Nat.sub(136n, Nat.mod(n, 136n)))

law digest_correct:
  for +s: T.State
  {C.digest_bytes(s) == F.squeeze(s) : List<&2, U32>}

def digest_correct(s):
  match s:
    case %(sp)s:
      {==}

law digest_length:
  for +s: T.State
  {List.length(&2, U32, C.digest_bytes(s)) == 32n : Nat}

def digest_length(s):
  match s:
    case %(sp)s:
      {==}

law keccak_correct:
  for +bytes: List<&2, U32>
  for +rounds: Nat
  {C.keccak(bytes, rounds) == F.keccak(bytes, rounds) : List<&2, U32>}

def keccak_correct(bytes, rounds):
  +n = List.length(&2, U32, bytes)
  %%suffix_correct(n) :
    {C.keccak(bytes, rounds) == F.squeeze(F.absorb(F.lanes(List.append(&2, U32, bytes, _)), rounds, F.initial())) : List<&2, U32>}
  +padded = List.append(&2, U32, bytes, C.suffix(n))
  %%lanes_correct(padded) :
    {C.keccak(bytes, rounds) == F.squeeze(F.absorb(_, rounds, F.initial())) : List<&2, U32>}
  %%absorb_correct(C.lanes(padded), rounds, C.zero()) :
    {C.keccak(bytes, rounds) == F.squeeze(_) : List<&2, U32>}
  digest_correct(C.absorb(C.lanes(padded), rounds, C.zero()))
''' % dict(lanes_for=lanes_for, L=L, Lsp=' '.join(LS), sp=sp, lp=lp, LP=' <> '.join(LS),
           short_lanes=short_lanes, B8=' <> '.join(B), short_bytes=short_bytes)


def main():
    (ROOT / 'src/crypto/sha3').mkdir(parents=True, exist_ok=True)
    (ROOT / 'src/crypto/sha3/core.bend').write_text(core())
    (ROOT / 'proofs/crypto/sha3').mkdir(parents=True, exist_ok=True)
    (ROOT / 'proofs/crypto/sha3/conformance.bend').write_text(conformance())


if __name__ == '__main__':
    main()
