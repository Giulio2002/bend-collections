def main():
    s = open(SRC).read()
    i = s.find('# ---- FUSED')
    if i >= 0:
        j = s.index('# ---- end FUSED') + len('# ---- end FUSED')
        s = s[:i] + src_section() + s[j:]
    else:
        old = '''def seal(+key: List<&2, U32>, +nonce: List<&2, U32>, +aad: List<&2, U32>, +pt: List<&2, U32>) -> List<&2, U32>:
  +ct = encrypt_ct(key, nonce, pt)
  List.append(&2, U32, ct, tag(key, nonce, aad, ct))'''
        assert old in s
        s = s.replace(old, old.replace('def seal(', 'def seal_ref(') + '\n\n' + src_section())
    i = s.find('# ---- FUSED OPEN')
    if i >= 0:
        j = s.index('# ---- end FUSED OPEN') + len('# ---- end FUSED OPEN')
        s = s[:i] + open_section() + s[j:]
    else:
        old = '''def open(+key: List<&2, U32>, +nonce: List<&2, U32>, +aad: List<&2, U32>, +data: List<&2, U32>) -> Maybe<&2, List<&2, U32>>:
  match data:
    case x0 <> x1 <> x2 <> x3 <> x4 <> x5 <> x6 <> x7 <> x8 <> x9 <> x10 <> x11 <> x12 <> x13 <> x14 <> x15 <> rest:
      open_split(key, nonce, aad, body(rest, data), tail(rest, data))
    case _: None{}'''
        assert old in s
        s = s.replace(old, old.replace('def open(', 'def open_ref(') + '\n\n' + open_section())
    open(SRC, 'w').write(s)
    pr = proof()
    # fpart goes before fseal_eq
    out = []
    for l in pr.split('\n'):
        if l.endswith('case Nil{}: ') :
            ind = l[:len(l) - len(l.lstrip())]
            out.append(ind + 'case Nil{}:')
            out.append(ind + '  match st:')
            out.append(ind + '    case C.S{%s}: {==}' % ', '.join(W))
        elif l == 'MATCHST':
            continue
        else:
            out.append(l)
    pr = '\n'.join(out)
    k = pr.index('law fseal_eq1:')
    pr = pr[:k] + fstep() + '\n' + pr[k:]
    op = fix_nil_leaves(open_proof())
    open(PRF, 'w').write(pr + '\n' + top() + '\n' + op + '\n' + open_top())



