def olets(ind, h='h', cnt='cnt'):
    """the four ciphertext blocks x0..x63 absorbed (g1..g4) and the count"""
    L = []
    prev = h
    for b in range(4):
        L.append('+g%d = L.block(kk, %s, L.load(%s, pone))' % (b + 1, prev, ', '.join('L.byte(x%d)' % (16 * b + j) for j in range(16))))
        prev = 'g%d' % (b + 1)
    L.append('+cnt4 = Nat.add(Nat.add(Nat.add(Nat.add(%s, 16n), 16n), 16n), 16n)' % cnt)
    return [ind + l for l in L]


