#!/usr/bin/env python3
"""Generate the fused ChaCha20-Poly1305 seal (one pass: each 64-byte
keystream block is XORed onto the plaintext and its four 16-byte
ciphertext blocks absorbed at once) and its proof.

  python3 tools/generators/aead_fused.py

rewrites the section between the FUSED markers of
src/crypto/aead/chacha20poly1305.bend and proofs/crypto/aead/fused.bend.
Nothing here is trusted: the checker verifies the generated proof.
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'src', 'crypto', 'aead', 'chacha20poly1305.bend')
PRF = os.path.join(ROOT, 'proofs', 'crypto', 'aead', 'fused.bend')

X = ['x%d' % i for i in range(64)]
Y = ['y%d' % i for i in range(64)]
W = ['w%d' % i for i in range(16)]


def ybytes(i):
    w = 'w%d' % (i // 4)
    return ['U32.and(%s,255)' % w, 'U32.and(U32.shrn(%s,8n),255)' % w, 'U32.and(U32.shrn(%s,16n),255)' % w, 'U32.shrn(%s,24n)' % w][i % 4]


def lets(ind, kk='kk', h='h', cnt='cnt'):
    L = []
    for i in range(64):
        L.append('+y%d = U32.xor(x%d, %s)' % (i, i, ybytes(i)))
    prev = h
    for b in range(4):
        L.append('+h%d = L.block(%s, %s, L.load(%s, pone))' % (b + 1, kk, prev, ', '.join('L.byte(y%d)' % (16 * b + j) for j in range(16))))
        prev = 'h%d' % (b + 1)
    L.append('+cnt4 = Nat.add(Nat.add(Nat.add(Nat.add(%s, 16n), 16n), 16n), 16n)' % cnt)
    return [ind + l for l in L]


def src_section():
    L = []
    L.append('# ---- FUSED (generated by tools/generators/aead_fused.py; do not edit)')
    L.append('''
# The end of the tag computation: the ciphertext's last bytes ct absorbed
# with their padding onto h (cnt bytes so far), then the two lengths.
def ftail(+ct: List<&2, U32>, +pone: Nat, +kk: L.K, sv: L.F, la: Nat, h: L.F, cnt: Nat) -> List<&2, U32>:
  List.append(&2, U32, ct, P.tag_len(pone, kk, sv, la, P.absorb_pad(pone, ct, kk, h, cnt)))

# The ciphertext of the last 0..63 bytes (st: the keystream state of the
# block under counter c).
def fct(fuel: Nat, xs: List<&2, U32>, +st: C.State, +r: Nat, +k: CH.Key, +c: U32, +n: CH.Nonce) -> List<&2, U32>:
  match fuel:
    case 0n: Nil{}
    case 1n+p: CH.xstream(p, C.bytes(st), xs, r, k, U32.add(c, 1), n)

# ciphertext || tag in one pass: st is the keystream state of the block
# under counter c; each full 64-byte block of xs is XORed with it and its
# four 16-byte ciphertext blocks absorbed onto h at once. The next state is
# computed only when bytes follow the block.
def fseal(fuel: Nat, xs: List<&2, U32>, +st: C.State, +r: Nat, +k: CH.Key, +c: U32, +n: CH.Nonce, +pone: Nat, +kk: L.K, +sv: L.F, +la: Nat, h: L.F, cnt: Nat) -> List<&2, U32>:
  match fuel xs st:''')
    L.append('    case 1n+p %s <> x64 <> rest C.S{%s}:' % (' <> '.join(X), ', '.join('+' + w for w in W)))
    L.extend(lets('      '))
    L.append('      +c1 = U32.add(c, 1)')
    L.append('      %s <> fseal(p, x64 <> rest, C.block(r, CH.state(k, c1, n)), r, k, c1, n, pone, kk, sv, la, h4, cnt4)' % ' <> '.join(Y))
    L.append('    case 1n+p %s <> Nil{} C.S{%s}:' % (' <> '.join(X), ', '.join('+' + w for w in W)))
    L.extend(lets('      '))
    L.append('      %s <> ftail(Nil{}, pone, kk, sv, la, h4, cnt4)' % ' <> '.join(Y))
    L.append('    case _ _ _:')
    L.append('      ftail(fct(fuel, xs, st, r, k, c, n), pone, kk, sv, la, h, cnt)')
    L.append('''
# seal after the aad: ciphertext || tag of pt, from the accumulator a over aad.
def sela(+pone: Nat, +kk: L.K, +sv: L.F, a: P.A, pt: List<&2, U32>, +k: CH.Key, +n: CH.Nonce) -> List<&2, U32>:
  match a pt:
    case P.A{h, la} Nil{}: ftail(Nil{}, pone, kk, sv, la, h, 0n)
    case P.A{h, la} +x <> +rest: fseal(List.length(&2, U32, x <> rest), x <> rest, C.block(10n, CH.state(k, 1, n)), 10n, k, 1, n, pone, kk, sv, la, h, 0n)

def selk(%s, aad: List<&2, U32>, pt: List<&2, U32>, +k: CH.Key, +n: CH.Nonce) -> List<&2, U32>:
  +kk = L.key(P.r_of(%s))
  sela(1n, kk, P.s_of(%s), P.absorb_pad(1n, aad, kk, L.zero(), 0n), pt, k, n)

def sell(pk: List<&2, U32>, aad: List<&2, U32>, pt: List<&2, U32>, +k: CH.Key, +n: CH.Nonce) -> List<&2, U32>:
  match pk:
    case %s <> rest: selk(%s, aad, pt, k, n)
    case _: Nil{}

# ciphertext || tag (RFC 8439 2.8) in one pass over the plaintext;
# proofs/crypto/aead/fused.bend proves it equal to seal_ref.
def seal(+key: List<&2, U32>, +nonce: List<&2, U32>, +aad: List<&2, U32>, +pt: List<&2, U32>) -> List<&2, U32>:
  sell(P.pad(32n, poly_key(key, nonce)), aad, pt, CH.key(key), CH.nonce(nonce))
# ---- end FUSED''' % (', '.join('+k%d: U32' % i for i in range(32)), ', '.join('k%d' % i for i in range(16)), ', '.join('k%d' % i for i in range(16, 32)),
                        ' <> '.join('k%d' % i for i in range(32)), ', '.join('k%d' % i for i in range(32))))
    return '\n'.join(L)


def nested(ind, depth, nil_fn, leaf_fn, var='x', tl='t', head='xs', last_rest='rest', start=0):
    """match head as depth cells: nil_fn(j) at a Nil after j cells, leaf_fn at depth cells"""
    L = [ind + 'match %s:' % head, ind + '  case Nil{}: ' + nil_fn(0)]
    cur = ind + '  '
    for j in range(depth):
        t = '%s%d' % (tl, j) if j < depth - 1 else last_rest
        L.append(cur + 'case +%s%d <> +%s:' % (var, start + j, t))
        if j < depth - 1:
            L.append(cur + '  match %s%d:' % (tl, j))
            L.append(cur + '    case Nil{}: ' + nil_fn(j + 1))
            cur += '    '
        else:
            L.extend(leaf_fn(cur + '  '))
    return L


FUEL_TEXT = 'law fseal_eq:\n  for fuel: Nat\n  for +xs: List<&2, U32>\n  for +st: C.State\n  for +r: Nat\n  for +k: CH.Key\n  for +c: U32\n  for +n: CH.Nonce\n  for +pone: Nat\n  for +kk: L.K\n  for +sv: L.F\n  for +la: Nat\n  for +h: L.F\n  for +cnt: Nat\n  {I.fseal(fuel, xs, st, r, k, c, n, pone, kk, sv, la, h, cnt) == I.ftail(I.fct(fuel, xs, st, r, k, c, n), pone, kk, sv, la, h, cnt) : List<&2, U32>}\n\ndef fseal_eq(fuel, xs, st, r, k, c, n, pone, kk, sv, la, h, cnt):\n  match fuel:\n    case 0n: {==}\n    case 1n+p: fseal_eq1(p, xs, st, r, k, c, n, pone, kk, sv, la, h, cnt)\n'


B1 = 'C.block(r, CH.state(k, U32.add(c, 1), n))'
C1 = 'U32.add(c, 1)'
C4 = 'Nat.add(Nat.add(Nat.add(Nat.add(cnt, 16n), 16n), 16n), 16n)'


def ycell(i):
    return 'U32.xor(x%d, %s)' % (i, ybytes(i))


def H4():
    prev = 'h'
    for b in range(4):
        prev = 'L.block(kk, %s, L.load(%s, pone))' % (prev, ', '.join('L.byte(%s)' % ycell(16 * b + j) for j in range(16)))
    return prev


