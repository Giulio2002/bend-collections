def loop(name, extra_h, concl, base, rec, absurd_ty, hyp=None):
    ls = ['def %s(%s, bs: List<&2, Nat>, +a: PX.PT, +r: PX.PT%s, +hb: {BV.all01(bs) == True{} : Bool}, +hq: {ok4(bs) == True{} : Bool}) -> %s:' % (name, hyp or HYP, extra_h, concl('bs', 'r', 'v')),
          '  match bs:', '    case Nil{}:', '      ' + base]
    for pat, lst in (('+b1 <> Nil{}', '[b1]'), ('+b1 <> +b2 <> Nil{}', '[b1, b2]'), ('+b1 <> +b2 <> +b3 <> Nil{}', '[b1, b2, b3]')):
        ls += ['    case %s:' % pat, '      Empty.absurd(%s, Lg.false_true(hq))' % absurd_ty(lst)]
    ls += ['    case +b1 <> +b2 <> +b3 <> +b4 <> +t:', SPLIT, rec]
    return '\n'.join(ls) + '\n'


