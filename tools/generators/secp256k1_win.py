import re
text = '\n'.join(o)
head, _, body = text.partition('\n# ---- on the specification')
body = '# ---- on the specification' + body
blocks = re.split(r'(?m)^(?=def |# ----)', body)
names = [re.match(r'def (\w+)', b).group(1) if b.startswith('def ') else None for b in blocks]
GROUP = re.compile(r'(?<![\w.])(GP|GS|G4|NP)\.|\bhp\b|\bhc\b')
defs = set(n for n in names if n)
free = set()
changed = True
while changed:
    changed = False
    for n, b in zip(names, blocks):
        if not n or n in free or GROUP.search(b):
            continue
        refs = set(re.findall(r'(?<![\w.])(\w+)\(', b)) & defs
        if refs - {n} <= free:
            free.add(n); changed = True
R, W = [], []
for n, b in zip(names, blocks):
    (R if n in free else W).append(b)
q = re.compile(r'(?<![\w.])(%s)(?=\()' % '|'.join(sorted(free, key=len, reverse=True)))
W = [q.sub(r'WR.\1', b) for b in W]
hl = head.split('\n')
imp = [l for l in hl if l.startswith('import ')]
rest = [l for l in hl if not l.startswith('import ')]
rimp = [l for l in imp if not re.search(r' as (GP|GS|G4|NP|C|NA)$', l)]
